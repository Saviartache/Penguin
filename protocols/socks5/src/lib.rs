//! SOCKS5: прокси общего назначения, описанный в RFC 1928 и RFC 1929.
//!
//! ## Что это за протокол
//!
//! Самый простой из всех, какие бывают: клиент открывает TCP-соединение до
//! прокси, договаривается о способе проверки подлинности, называет адрес
//! назначения — и дальше по тому же соединению идут байты приложения как
//! есть. Никакого шифрования у SOCKS5 нет вовсе.
//!
//! Отсюда область применения. SOCKS5 — это выход через **свой** прокси:
//! туннель `ssh -D`, соседний контейнер, локальный клиент другого протокола.
//! Отдавать в него трафик через враждебную сеть незачем: он весь виден по
//! дороге, включая имя сервера назначения.
//!
//! ## Что отсюда следует для клиента
//!
//! **Соединение на каждое подключение.** Мультиплексирования нет: каждое
//! приложение получает свой TCP-поток до прокси. Поэтому [`Socks5Outbound`]
//! ничего не держит между вызовами — он только помнит настройки.
//!
//! **UDP отдельным каналом.** Команда `UDP ASSOCIATE` открывает не поток, а
//! разрешение слать датаграммы на выданный прокси адрес; каждая посылка при
//! этом несёт свой заголовок с адресом назначения ([`frame::udp`]). Управляющее
//! TCP-соединение при этом обязано жить: закроется оно — пропадёт и канал.
//!
//! **Имя уезжает на ту сторону.** Адрес назначения передаётся доменом
//! (`ATYP = 3`), и разрешает его прокси. Без этого правило «youtube.com в
//! тоннель» теряло бы смысл на последнем шаге.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound ──┬─► handshake  приветствие, пароль, команда
//!                         └─► datagram   UDP поверх выданного канала
//!  frame — разбор и сборка байт, ничего не знает об остальном
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`] и [`penguin_proto`]. Сокетов он не
//! открывает: их выдаёт [`penguin_proto::dialer::Dialer`] — иначе пакеты к
//! прокси ушли бы в собственный, ещё не поднятый тоннель.

