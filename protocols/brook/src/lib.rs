//! Brook: простой протокол поверх TCP и UDP, AES-256-GCM, нонс с меткой времени.
//!
//! ## Что это за протокол
//!
//! У Brook нет отдельного рукопожатия и отдельного кадра для заголовка: первый
//! кусок TCP-потока — это метка времени и адрес назначения, зашифрованные тем
//! же способом, что и все остальные куски. Ключ каждого направления выводится
//! HKDF-SHA256 прямо из пароля и своего же нонса — без главного ключа, как у
//! Shadowsocks, и без Argon2id, как у Snell. Подробности формата и то, откуда
//! взята каждая константа, — в [`frame`].
//!
//! ## Чем это отличается от `penguin_transport::aead`
//!
//! Общий кадр ([`penguin_transport::aead`]) режет поток на куски точно так же
//! — длина под своей меткой, данные под своей, — но нонс там всегда начинает
//! счёт с нуля, а соль нужна только для вывода ключа. У Brook нонс **и есть**
//! соль: одни и те же двенадцать случайных байт идут и на вход HKDF, и прямо
//! в счётчик AES-GCM, а следующее значение считается по-своему — движутся
//! только первые восемь байт ([`frame::nonce`]). Это разница не в цифрах, а в
//! устройстве, поэтому крейт несёт свой шифр, а не подключает общий.
//!
//! ## Про метку времени
//!
//! Каждое TCP-соединение и каждая датаграмма UDP несут метку времени в первом
//! куске, которую сервер сверяет со своими часами и отвергает, если она отстала
//! больше чем на минуту (`streamserver.go`, `packetserverconn.go`). Отдельного
//! сигнала об этом сервер не даёт — см. документ [`error::BrookError`], — но
//! текст ошибки называет часы прямо, потому что для человека расхождение часов
//! выглядит как «сеть не работает», а не как то, чем оно является на самом
//! деле.
//!
//! ## Источник
//!
//! Официального описания формата у Brook, кроме кода, почти нет: единственный
//! документ — `protocol/brook-server-protocol.md` в самом репозитории эталона,
//! и в этом крейте он совпадает с кодом (`streamclient.go`, `packetclient.go`,
//! `nonce.go`, `init.go`) во всём до последнего байта. Ревизия эталона —
//! `txthinking/brook`, ветка `master`, коммит
//! `5cd13ef3b1fb574e88ebf2c1b5d95f2ebe1342c8` (релиз `v20260101.0`).
//!
//! ## Что не реализовано
//!
//! **QUIC** (`quicclient` эталона). Решение по плану: экзотика ложится на
//! QUIC отдельным трудом, сравнимым с новым протоколом, и здесь пропущена.
//!
//! **«UDP поверх TCP».** У эталона это отдельный режим для клиентов за
//! рестриктивным NAT: та же метка кадра TCP, но с нечётной секундой вместо
//! чётной ([`frame::tcp::tcp_timestamp`]), и множество датаграмм внутри одного
//! потока, различаемых собственной таблицей соответствий. Настоящий UDP
//! ([`datagram`]) решает ту же задачу проще и без этой таблицы; вариант
//! добавляется отдельно, если когда-нибудь понадобится клиентам без прямого
//! UDP наружу.
//!
//! ## Устройство
//!
//! ```text
//!  factory ─► outbound ─► carry      сокет, при необходимости WebSocket и TLS
//!               │          handshake  свой нонс, чужой нонс, первый кусок
//!               │
//!               ├────► stream    поток приложения, кадр TCP
//!               └────► datagram  один сокет UDP, своя соль на посылку
//!  frame — разбор и сборка байт, без сети
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

