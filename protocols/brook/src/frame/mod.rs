//! Разбор и сборка байт Brook. Ни сети, ни `tokio` — только срезы и векторы.
//!
//! ```text
//!  nonce   двенадцать байт: соль для ключа и первое значение счётчика разом
//!  key     HKDF-SHA256(пароль, нонс, "brook") — без главного ключа
//!  cipher  AES-256-GCM с нонсом по правилам Brook, а не общего кадра
//!  tcp     кадр потока: длина под меткой, кусок под меткой, метка времени первым куском
//!  udp     кадр датаграммы: вся посылка — один кусок, нонс не переиспользуется
//! ```
//!
//! # Источник
//!
//! `txthinking/brook`, ветка `master`, ревизия `5cd13ef3b1fb574e88ebf2c1b5d95f2ebe1342c8`
//! (соответствует релизу `v20260101.0`). Формат подтверждён и кодом
//! (`streamclient.go`, `packetclient.go`, `nonce.go`, `init.go`), и
//! официальным описанием сервера (`protocol/brook-server-protocol.md`) — они
//! не расходятся ни в одной константе, что для протокола без стороннего
//! разбора большая редкость. Расхождений между источниками в этом крейте нет;
//! там, где решение всё же принималось (например, не реализовывать «UDP поверх
//! TCP»), это отмечено в документе конкретного модуля.

