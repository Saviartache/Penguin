//! TrustTunnel: `CONNECT` поверх HTTP/2 или HTTP/3, без своего рукопожатия.
//!
//! ## Что это за протокол
//!
//! VPN-протокол AdGuard, выложенный в открытый доступ в феврале 2026 года.
//! Своего рукопожатия у него нет вовсе: TCP-соединение туннелируется обычным
//! HTTP `CONNECT` поверх HTTP/2 (ALPN `h2`) или HTTP/3 (ALPN `h3`); вся
//! конфиденциальность — на TLS/QUIC, а сверху протокол добавляет только
//! маршрутизацию соединений и мультиплексирование UDP и ICMP одним потоком
//! на каждый вид трафика.
//!
//! Этот крейт реализует обе ноги — TCP через `CONNECT`, UDP через
//! псевдо-хост `_udp2`, проверку живости через `_check` — без ICMP. Нога
//! выбирается полем `transport` (`h2` или `h3`); автоматического выбора
//! (§3.3) нет. Подробности — в разделе «Чего нет и почему» ниже.
//!
//! ## Источники и сверка
//!
//! - `PROTOCOL.md` версии 1.0 (24 декабря 2025) из
//!   `github.com/TrustTunnel/TrustTunnel` — формальная спецификация,
//!   написанная под сторонние реализации, а не пересказ.
//! - `lib/src/` того же репозитория (Rust, ветка `main`, снимок на день
//!   сверки — сентябрь 2026) — сама протокольная библиотека сервера.
//!   Разбор строился на спецификации, а код проверялся везде, где документ
//!   был неточен или недостаточен: конкретно — `http_udp_codec.rs` (раскладка
//!   кадров UDP), `net_utils.rs` (запись адреса), `http_downstream.rs`
//!   (сопоставление `:authority` с `_udp2`/`_check`, код ответа при
//!   провале опознания), `settings.rs` (умолчания).
//!
//! Расхождение между текстом и кодом ровно одно, и оно задокументировано на
//! месте, а не только здесь: [`udp::frame`], раздел «Расхождение с текстом
//! спецификации» — определение того, что считать IPv4-адресом в 16-байтовом
//! поле. Спецификация (§11.2) обещает исключение для `::1`, эталон его не
//! делает; этот крейт повторяет эталон.
//!
//! ## Устройство
//!
//! ```text
//! factory ──► outbound ──┬─► transport::link (HTTP/2 или HTTP/3: открыть CONNECT)
//!                        │      ├─► transport::h2 (TCP + TLS + h2)
//!                        │      └─► transport::h3 (QUIC + HTTP/3)
//!                        ├─► connect      (запрос CONNECT, разбор кода ответа)
//!                        └─► udp::session (единый поток _udp2, разбор по сессиям)
//!                                 │
//!                            udp::frame   (сборка и разбор кадров — без сети)
//! ```
//!
//! Ни `connect`, ни `udp::session` не знают, по какой ноге идёт поток и что
//! он открывает — TCP-адрес или псевдо-хост: всё это один и тот же
//! `CONNECT`, отличается только `:authority`. HTTP/3 — свой, из
//! [`penguin_transport::h3`]; его поток уже `AsyncRead + AsyncWrite`.
//!
//! ## Возможности
//!
//! `capabilities().udp` — `true`: UDP ходит внутри той же ноги отдельным
//! потоком `_udp2`, а не отдельным транспортом. `multiplex` — `true` по той
//! же причине, что у `protocols/naive`: TLS или QUIC поднимается один раз на
//! весь профиль, а не на каждое соединение.
//!
//! ## Чего нет и почему
//!
//! - **Автовыбор ноги** (§3.3: попробовать HTTP/3, через секунду — HTTP/2).
//!   Спецификация его разрешает, а не требует; нога задаётся настройкой.
//!   Гонка двух рукопожатий — это поведение `supervisor`, а не протокола,
//!   так же как график переподключения ниже.
//! - **ICMP.** У [`penguin_proto::outbound::Outbound`] есть только
//!   `connect_tcp` и `bind_udp` — девать разобранные ICMP-кадры некуда,
//!   протокол уровня трейта такого не предусматривает (та же история, что с
//!   DTLS в фазе 21 у `masque`). Интеропу ICMP тоже не нужен.
//! - **Заголовок `user-agent` по форме спецификации.** §5.1 предписывает
//!   `<platform> <app_name>`; здесь всегда одна и та же константа. Причина —
//!   в [`connect`]: сервер-эталон использует это поле только как метку для
//!   метрик, не для маршрутизации или опознания, а платформу и имя
//!   приложения, породившего конкретный поток, крейт протокола не видит и
//!   видеть не должен (`AGENTS.md`, §1.1).
//! - **Собственный график переподключения.** §10.3 описывает экспоненциальный
//!   рост задержки между попытками — это забота вызывающего
//!   (`supervisor`), а не протокола: ни один другой крейт `protocols/*` в
//!   этом дереве не планирует свои повторные попытки сам, и заводить здесь
//!   первое исключение значило бы одним протоколом решать за клиента, когда
//!   ему разрешено пробовать снова.
//! - **Отслеживание бездействия для проверки живости.** §8.4 запускает
//!   `_check`, когда данные не приходили `timeout_ms`; этот крейт вместо
//!   этого стучится с тем же периодом безусловно — подробности и цена
//!   упрощения в [`outbound`], у константы срока проверки.
//!
//! Своего отпечатка `ClientHello` протокол не требует — `protocols/utls` не
//! нужен ни здесь, ни в интеропе.
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает — ни TCP, ни UDP: их
//! выдаёт [`penguin_proto::dialer::Dialer`], иначе рукопожатие ушло бы в
//! собственный, ещё не поднятый тоннель.

