//! Mieru: своё шифрование поверх голого TCP, своё мультиплексирование,
//! адрес назначения — обычным SOCKS5 внутри тоннеля.
//!
//! ## Источник
//!
//! Формат целиком взят из `github.com/enfein/mieru` (ветка `main`, сверено
//! в сентябре 2026 года): `docs/protocol.md` — сегменты, метаданные, ключ; и
//! исходники — `pkg/cipher/{cipher,keygen,api}.go` (нонс, вывод ключа),
//! `pkg/protocol/{metadata,session,segment}.go` (числа команд, раскладка
//! полей, сколько сессия несёт данных до подтверждения). У Mieru, в отличие
//! от Snell, есть документация — но не на всё: как устроен внутри тоннеля
//! адрес назначения, в ней нет ни слова (см. ниже).
//!
//! ## Что это за протокол
//!
//! Клиент делит поток приложения на сегменты и шифрует каждый
//! XChaCha20-Poly1305 отдельно — метаданные (32 байта: тип, номер сессии,
//! порядковый номер, длины) отдельной операцией AEAD от полезной нагрузки.
//! Ключ выводится не из общего секрета, а из имени пользователя, пароля и
//! текущего времени, округлённого до двух минут (`keying`), — поэтому
//! рукопожатия в привычном смысле нет: сервер либо расшифровывает первый
//! сегмент чьим-то ключом, либо нет.
//!
//! Сколько угодно сессий (то есть потоков приложения) уживаются на одном
//! TCP-соединении (`underlay`) — свой мультиплексор, как у AnyTLS, но проще:
//! нет отдельной команды «конец всего соединения», сессии просто открываются
//! и закрываются порознь.
//!
//! ## У протокола нет поля адреса назначения
//!
//! Ни один из трёх видов метаданных (`metadata`) не несёт адрес: `mieru`
//! задуман как транспорт для локального SOCKS5/HTTP-клиента до сервера
//! `mita`, который сам умеет SOCKS5 (`pkg/socks5/handler.go` эталона читает
//! обычное приветствие и запрос `CONNECT`). Поэтому адрес назначения внутри
//! открытой сессии передаётся обычным протоколом SOCKS5 (`socks5`) — не
//! потому, что так решили мы, а потому, что так читает эталонный сервер.
//!
//! ## Расхождения источников
//!
//! - **Шифр.** `docs/protocol.md` говорит «протокол допускает любой AEAD»,
//!   но код признаёт только `XChaCha20Poly1305`; `AES128GCM`, `AES256GCM` и
//!   обычный `ChaCha20Poly1305` в `pkg/cipher/cipher.go` явно помечены
//!   `// Not supported`. Взят код.
//! - **Округление времени.** Документ говорит «округлить до ближайших двух
//!   минут» без деталей; код (`saltFromTime`) округляет через `time.Round`
//!   средствами Go. Мы округляем к ближайшему кратному 120 секундам от нуля
//!   прочь на границе — см. `keying::round_to_nearest` и его тест: разница
//!   способна сказаться только на секунде ровно посередине окна, а допуск
//!   между часами клиента и сервера и так четыре минуты.
//!
//! ## Чего в этой сборке нет
//!
//! - **UDP.** Датаграммный режим Mieru — отдельный набор правил (нонс на
//!   каждый пакет, свой предел длины по MTU сети) поверх отдельного
//!   транспорта. Не реализован; `capabilities().udp` — `false`, а не
//!   молчаливая ложь.
//! - **Расширение с низкой энтропией** (`docs/protocol.md`, «Low Entropy
//!   Payload Encoding») — необязательная обфускация формы байт полезной
//!   нагрузки. Сегмент такого вида (`protocolType` 10 и 11) мы не строим и,
//!   если он придёт, отказываемся его понять (`metadata::Metadata::decode`),
//!   а не гадаем формат.
//! - **Дополнение (padding) и обфускация трафика.** Каждый исходящий сегмент
//!   несёт дополнение нулевой длины. У эталона есть настраиваемая схема,
//!   маскирующая длины и энтропию под конкретный образец трафика
//!   (`docs/traffic-pattern.md`) — отдельная, самостоятельная по цене
//!   возможность, не часть проверки подлинности или доставки данных.
//! - **Управление окном отправки.** Сервер шлёт `unAckSeq`/`windowSize` в
//!   каждом сегменте данных и подтверждении; мы их разбираем, но не
//!   ограничиваем ими собственную отправку — подробности и обоснование в
//!   документе модуля `underlay`.
//! - **Смена порта и TLS.** У Mieru их нет вовсе — не сокращение, а
//!   свойство протокола.
//!
//! Половинчатый режим хуже отсутствующего: там, где не хватило времени
//! сделать целиком, сборка честно отказывает (`UdpUnsupported`), а не делает
//! вид, что умеет.
//!
//! ## Устройство
//!
//! ```text
//!  factory ─► outbound ─► pool ──► connector      TCP, без TLS
//!                          │
//!                          └────► underlay ─┬─► сегмент за сегментом,
//!                                            │   шифр направления (cipher)
//!                                            └─► stream   сессия приложения
//!
//!  keying, nonce, cipher, metadata, segment, socks5 — разбор и сборка байт,
//!  без сети
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`] (только `deadline` и `addr::socks` — своего TLS и
//! своего AEAD-обрамления у Mieru нет, отсюда нет `penguin_transport::tls`
//! и `penguin_transport::aead`, чей нонс короче, чем требует этот протокол).
//! Сокетов крейт не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

