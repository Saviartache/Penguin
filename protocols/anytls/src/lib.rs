//! AnyTLS: мультиплексор внутри TLS со своей схемой дополнения.
//!
//! ## Что это за протокол
//!
//! Снаружи — обычное соединение TLS. Внутри — сессия, которая несёт сколько
//! угодно потоков сразу: каждый кадр подписан номером потока, и открытие
//! нового стоит семи байт вместо целого рукопожатия.
//!
//! Отличает AnyTLS от Trojan и VLESS не это, а вторая половина замысла:
//! **размеры записей TLS**. Прокси, который просто пересылает байты, режет
//! поток на записи не так, как браузер, — и по одним размерам, не расшифровав
//! ни байта, соединение опознаётся. AnyTLS задаёт размеры первых записей
//! схемой, которую присылает сервер (см. [`padding`]). Схему можно поменять у
//! всех клиентов сразу, поэтому известной она бывает недолго.
//!
//! ## Что отсюда следует для клиента
//!
//! **Неверный пароль не отличить от верного.** Ответа на опознание нет:
//! сервер, не узнавший отпечаток, закрывает соединение или отдаёт наши байты
//! сайту, за который себя выдаёт. `AuthRejected` вернуть неоткуда — как и у
//! Trojan, и по той же причине.
//!
//! **Полузакрытия нет.** `cmdFIN` закрывает поток целиком, в обе стороны.
//! Поэтому `poll_shutdown` потока его не шлёт, и приложение, которое ждёт
//! ответа после «я всё сказал», через AnyTLS его не дождётся. Это свойство
//! протокола.
//!
//! **Схема дополнения — настройка сервера.** Поля в форме нет: присланная
//! сервером схема заменяет любую, какую можно было бы задать.
//!
//! ## UDP
//!
//! Своего способа возить датаграммы у протокола нет. Берётся `udp-over-tcp`
//! версии 2 из `sing-box`: поток к особому имени, и в нём пары «адрес,
//! данные» (см. [`uot`]). Адрес там записан **третьим** способом — не тем,
//! что в SOCKS5, и не тем, что в VLESS.
//!
//! ## Устройство
//!
//! ```text
//!  factory ─► outbound ─► pool ──► connector   TLS и опознание
//!                          │
//!                          └────► session ─┬─► writer   дополнение записей
//!                                          ├─► reader   разбор кадров
//!                                          └─► stream   поток приложения
//!  frame, kv, padding, uot — разбор и сборка байт, без сети
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

