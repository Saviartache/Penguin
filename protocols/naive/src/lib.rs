//! NaiveProxy: `CONNECT` поверх HTTP/2, с дополнением трафика.
//!
//! ## Что это за протокол
//!
//! Тот же `CONNECT`, что у `http`/`https` (`penguin-http-proxy`), только не
//! по HTTP/1.1, а по HTTP/2. Разница в транспорте — это и есть маскировка:
//! снаружи соединение неотличимо от обычного браузера, зашедшего на
//! веб-сервер за HTTP/2, а не от прокси с характерным HTTP/1.1-разговором.
//!
//! Сверху — вторая маскировка, уже не на уровне протокола, а на уровне
//! размеров: [`padding`] добивает первые кадры туннеля до случайной длины,
//! чтобы длина CONNECT-обмена и первых пакетов приложения не выдавала прокси
//! статистически, даже если TLS уже скрыл содержимое.
//!
//! ## Почему это отдельный крейт, а не часть `http-proxy`
//!
//! Схема дополнения и кадровый разговор по HTTP/2 (`h2`) — это код, которым
//! простой `CONNECT` по TCP (`http`/`https`) никогда не пользуется. Держать
//! их в одном крейте значило бы, что профиль с обычным HTTP-прокси платит за
//! то, что у него не выполнится ни разу.
//!
//! ## Сверка со эталоном
//!
//! Схема дополнения не придумана, а снята с исходников `klzgrad/naiveproxy`
//! (форк Chromium; интересующая часть — `src/net/tools/naive/`), тег
//! `v150.0.7871.63-1` (соответствует ветке `master` на момент сверки,
//! 2026-07-03). Подробности, номера строк и то, что удалось сверить
//! независимо, — в документации модуля [`padding`].
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound/h2 ──► transport/h2 (TCP + TLS + h2)
//!
//!  connect   запрос CONNECT и разбор кода ответа
//!  padding   заголовки согласования и дополнение первых кадров
//!  stream    AsyncRead+AsyncWrite поверх кадров h2
//! ```
//!
//! ## Возможности
//!
//! `capabilities().udp` — всегда `false`: `CONNECT` не переносит датаграмм
//! ни в каком виде. Соврать здесь значило бы, что DNS-запрос уйдёт в
//! направление, которое молча его потеряет (`AGENTS.md`, договор
//! [`penguin_proto::capabilities::Capabilities`]). `multiplex` — `true`:
//! рукопожатие TLS с сервером происходит один раз на весь профиль, а каждое
//! приложение получает свой поток `CONNECT` внутри уже поднятого соединения.
//!
//! ## Что не реализовано и почему
//!
//! - **`CONNECT` поверх HTTP/3.** Классический `CONNECT` обязан идти без
//!   `:scheme` и `:path` (RFC 9114, §4.4), а `h3` 0.0.8 — последний
//!   опубликованный выпуск — посылает их всегда, и сервер отвечает
//!   `H3_MESSAGE_ERROR`. Обойти это со стороны крейта нечем: заголовки
//!   собирает библиотека. В `master` апстрима исправлено (`hyperium/h3`,
//!   коммит `e07e694`); выпуска с фиксом нет, и до него нога HTTP/3 здесь
//!   не живёт.
//! - **Заголовок `fastopen`.** В эталоне он посылается только после того,
//!   как тип дополнения для сервера уже был согласован ранее, — это
//!   оптимизация задержки повторных соединений, а не часть схемы дополнения,
//!   и `plan.md` её не требует.
//! - **Обрамление `RST_STREAM` в HTTP/2** (эталон подсовывает перед сбросом
//!   потока поддельный кадр `DATA`, чтобы пара кадров выглядела как
//!   `HEADERS`). Это код самого Chromium (`net/spdy/spdy_session.cc`), а не
//!   `net/tools/naive/`, и относится к тому, как сессия сбрасывает **чужой**
//!   поток, — в клиенте, который сам потоки не сбрасывает, применить его
//!   не к чему.
//! - **Значение заголовка `padding` из таблицы HPACK.** Эталон набирает его
//!   кодами, не входящими в статическую таблицу и не сжимаемыми Хаффманом
//!   (`padding_utils.cc`), — здесь используется обычный случайный ASCII.
//!   Сервер содержимое не проверяет, только наличие заголовка, поэтому на
//!   совместимость это не влияет — подробности в документации [`padding`].
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает — ни TCP, ни UDP: их
//! выдаёт [`penguin_proto::dialer::Dialer`], иначе рукопожатие ушло бы в
//! собственный, ещё не поднятый тоннель.

