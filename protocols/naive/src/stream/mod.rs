//! `AsyncRead + AsyncWrite` поверх кадров HTTP/2 и HTTP/3.
//!
//! Обе библиотеки, `h2` и `h3`, отдают тело потока не тем интерфейсом, к
//! которому привык остальной клиент, — своим, кадровым и по большей части
//! асинхронным, а не через `poll_*`. Здесь это разница стирается: снаружи
//! оба выглядят обычным потоком байт, поверх которого дальше накладывается
//! [`crate::padding::PaddedStream`].

pub mod h2;
pub mod h3;

use std::io;

/// Приводит ошибку библиотеки кадров к языку `AsyncRead`/`AsyncWrite`.
///
/// Общая для `h2` и `h3`: обе ошибки чужие для этого крейта и превращаются в
/// одно и то же — «что-то пошло не так на уровне кадров», а не в конкретный
/// вариант [`crate::error::NaiveError`]. Ту работу дальше по стеку делает
/// [`crate::connect::perform`] и разбор кода ответа; на уровне отдельного
/// байта потока различать их уже не для чего.
pub(crate) fn to_io_error(err: impl std::error::Error + Send + Sync + 'static) -> io::Error {
    io::Error::other(err)
}
