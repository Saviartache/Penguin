//! `AsyncRead + AsyncWrite` поверх кадров HTTP/2.
//!
//! Библиотека `h2` отдаёт тело потока не тем интерфейсом, к которому привык
//! остальной клиент, — своим, кадровым и по большей части асинхронным, а не
//! через `poll_*`. Здесь эта разница стирается: снаружи поток выглядит
//! обычным потоком байт, поверх которого дальше накладывается
//! [`crate::padding::PaddedStream`].

pub mod h2;

use std::io;

/// Приводит ошибку библиотеки кадров к языку `AsyncRead`/`AsyncWrite`.
///
/// Ошибка `h2` — чужая для этого крейта и превращается в «что-то пошло не
/// так на уровне кадров», а не в конкретный вариант
/// [`crate::error::NaiveError`]. Ту работу дальше по стеку делает
/// [`crate::connect::perform`] и разбор кода ответа; на уровне отдельного
/// байта потока различать их уже не для чего.
pub(crate) fn to_io_error(err: impl std::error::Error + Send + Sync + 'static) -> io::Error {
    io::Error::other(err)
}
