//! Рассинхронизация DPI: как отдать первую посылку так, чтобы разобрал её
//! сервер, а не оборудование по дороге.
//!
//! ```text
//!  plan   разбор настроек: стратегия, точки разреза, TTL
//!  write  сама отправка: разрез, перестановка, ложная посылка
//! ```
//!
//! # Откуда это взято
//!
//! Из `zapret2` (`github.com/bol-van/zapret2`) — набора приёмов, которыми
//! обходят DPI, ничего не меняя на той стороне. Идея у всех приёмов одна:
//! DPI собирает поток не так, как его собирает настоящий TCP, и на этой
//! разнице его можно оставить без того куска, по которому он принимает
//! решение, — без имени узла в `ClientHello`.
//!
//! # Что здесь есть и чего здесь нет
//!
//! `zapret2` работает **на пакетах**: `nfqws` берёт их из очереди ядра
//! (`NFQUEUE`, `WinDivert`) и правит заголовки TCP и IP руками. Отсюда его
//! `badsum`, `badseq`, `ipfrag`, `syndata`, `wssize`, `udp2icmp` — всё это
//! требует своего IP-заголовка и прав на сырой сокет.
//!
//! Здесь сокет обычный, и его выдаёт [`Dialer`](penguin_proto::dialer::Dialer)
//! (`AGENTS.md` §3). Поэтому взято ровно то, что делается из пространства
//! пользователя — то же подмножество, что и у `tpws`, второй половины
//! `zapret`:
//!
//! | Приём `zapret2`   | Здесь                | Чем сделано                  |
//! | ----------------- | -------------------- | ---------------------------- |
//! | `multisplit`      | [`Strategy::Multisplit`] | несколько `write` подряд |
//! | `multidisorder`   | [`Strategy::Disorder`]   | малый TTL на первый кусок |
//! | `fake`            | [`Strategy::Fake`]       | ложная посылка с малым TTL |
//! | `fakedsplit`      | [`Strategy::FakedSplit`] | то и другое сразу        |
//! | `badsum`, `badseq`, `ipfrag`, `syndata`, `wssize`, `udp2icmp` | нет | нужен сырой сокет |
//! | `autottl`         | нет                  | нужен TTL входящих пакетов   |
//!
//! Пустых обещаний здесь нет намеренно: стратегия, которая называется, но не
//! делает того, что означает её имя в `zapret2`, — худший вид настройки.
//! Неизвестное имя отвергается разбором, а не принимается молча.
//!
//! # Почему ложная посылка не ломает соединение
//!
//! У `nfqws` ложный пакет до сервера не доходит никогда: он подделан так, что
//! его отбрасывает либо маршрутизатор (малый TTL), либо сам сервер (неверная
//! контрольная сумма). Из пространства пользователя подделать контрольную
//! сумму нельзя, а малый TTL — это **не гарантия**: сервер за три перехода
//! ложную посылку получит, и ядро всё равно повторит её, если она потерялась.
//!
//! Отсюда правило, без которого приём был бы игрой в рулетку: **ложную
//! посылку должен уметь пропустить сервер**. Этот слой её не выдумывает — он
//! отправляет то, что дал протокол, а протокол обязан выбрать такую, которую
//! его сервер пропустит. У `penguin-pingwin` это лишний `ClientHello`, не
//! проходящий опознание, и сервер пропускает его по своему же правилу
//! («чужое приветствие — читаем дальше»), не заводя ради этого никакой
//! отдельной метки, которую можно было бы искать в трафике.

