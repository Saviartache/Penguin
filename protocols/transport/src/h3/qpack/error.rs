//! Ошибки разбора QPACK.

use thiserror::Error;

/// Ошибка разбора полей; для соединения всегда `QPACK_DECOMPRESSION_FAILED` (RFC 9204, §6).
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum QpackError {
    /// Блок кончился посреди представления.
    #[error("блок полей обрезан")]
    Truncated,

    /// Целое длиннее 62 бит (RFC 9204, §4.1.1).
    #[error("целое в блоке полей длиннее 62 бит")]
    Integer,

    /// Строка в коде Хаффмана не разбирается.
    #[error("строка в коде Хаффмана испорчена")]
    Huffman,

    /// Ссылка на динамическую таблицу (её ёмкость нулевая).
    #[error("ссылка на динамическую таблицу, которой нет")]
    Dynamic,

    /// Индекс за концом статической таблицы.
    #[error("в статической таблице нет записи {0}")]
    StaticIndex(u64),

    /// Блок больше объявленного предела.
    #[error("блок полей больше {0} байт")]
    TooLarge(usize),
}
