//! QPACK без динамической таблицы (RFC 9204).
//!
//! Клиенту туннеля динамическая таблица не окупается: запросов на
//! соединение немного, и почти все заголовки — разовые. Без неё QPACK —
//! это статическая таблица, литералы и код Хаффмана, а потоки кодировщика и
//! декодировщика не нужны вовсе.
//!
//! ```text
//!  static_table  99 записей из приложения A
//!  huffman       код из RFC 7541, приложение B
//!  primitive     целое с префиксом и строка
//!  field         блок полей: префикс и представления
//! ```

mod error;
pub mod field;
pub mod huffman;
pub mod primitive;
pub mod static_table;

