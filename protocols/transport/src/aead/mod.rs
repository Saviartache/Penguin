//! Поток, зашифрованный кусками: соль, длина, кусок, длина, кусок.
//!
//! ```text
//!  ──► [соль] [длина+метка] [кусок+метка] [длина+метка] [кусок+метка] ...
//!       ^^^^^^
//!       открытым текстом, один раз в начале
//! ```
//!
//! # Зачем это здесь
//!
//! Обрамление придумано для Shadowsocks, но им пользуется не только он: Snell
//! возит внутри него всё, что не v4, а различается у них не кадр, а вывод
//! ключа — HKDF против Argon2id. Написанное дважды, оно дважды даёт один и
//! тот же случай ответить по-разному на вопрос, что делать с длиной, которую
//! уже расшифровали.
//!
//! Отсюда разделение: кадр — здесь, вывод ключа — у протокола, и связывает их
//! [`Keying`].
//!
//! # Что внутри
//!
//! ```text
//!  algorithm  какие шифры бывают и какой длины у них ключ
//!  cipher     ключ и его счётчик: нонс считается, а не бросается
//!  keying     как из соли получается сеансовый ключ
//!  stream     сам поток
//! ```

pub mod algorithm;
pub mod cipher;
pub mod keying;
pub mod stream;

pub use algorithm::{Algorithm, NONCE_LEN, TAG_LEN};
pub use cipher::{Cipher, sealed_len};
pub use keying::Keying;
pub use stream::{ChunkStream, MAX_CHUNK, seal_chunk};
