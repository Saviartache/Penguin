//! WebSocket как транспорт: поток байт, притворяющийся веб-страницей.
//!
//! ```text
//!  handshake  просьба сменить протокол и проверка ответа
//!  frame      разбор и сборка кадров — чистые функции над срезами
//!  stream     AsyncRead + AsyncWrite поверх кадров
//! ```
//!
//! # Зачем он протоколу
//!
//! Соединение, идущее по 443 порту внутри TLS и выглядящее запросом
//! `GET /ws`, проходит там, где голый поток режут: для промежуточного узла это
//! обычный сайт с долгоживущим соединением. Той же дорогой ходят чат, биржевые
//! котировки и панель управления — то есть трафик, который не выключить.
//!
//! Платится за это заголовком на каждый кадр (от двух до четырнадцати байт) и
//! маскировкой — то есть проходом XOR по всему, что уходит. На фоне TLS это
//! незаметно.
//!
//! # Чего здесь пока нет
//!
//! **Ранних данных.** v2ray умеет положить первые байты прямо в путь запроса
//! или в `Sec-WebSocket-Protocol` и сэкономить целый оборот до сервера.
//! Заводится это поверх готового рукопожатия и добавляется тогда, когда
//! появится протокол, который этим пользуется (`plan.md`, фаза 5).
//!
//! **Сжатия (`permessage-deflate`).** Трафик внутри уже зашифрован, то есть
//! несжимаем; договариваться о сжатии значило бы платить за него впустую.

pub mod frame;
pub mod handshake;
pub mod stream;

pub use handshake::Request;
pub use stream::WsStream;

use tokio::io::{AsyncRead, AsyncWrite};

use crate::error::TransportResult;

/// Проводит рукопожатие и отдаёт готовый поток.
///
/// Всё, что нужно протоколу: на входе соединение до сервера, на выходе —
/// [`AsyncRead`] + [`AsyncWrite`], в который можно писать байты протокола.
pub async fn connect<S>(mut io: S, request: &Request) -> TransportResult<WsStream<S>>
where
    S: AsyncRead + AsyncWrite + Unpin,
{
    let tail = handshake::perform(&mut io, request).await?;
    Ok(WsStream::new(io, tail))
}
