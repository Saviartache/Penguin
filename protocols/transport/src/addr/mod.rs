//! Адрес назначения на проводе. Две записи, и обе нужны.
//!
//! | Запись | Кто ей пользуется |
//! |---|---|
//! | [`socks`] | SOCKS5, Trojan, Shadowsocks, Snell, Brook, GOST |
//! | [`v2ray`] | VLESS, VMess |
//!
//! Они похожи ровно настолько, чтобы их спутать, и различаются в двух местах:
//! у [`v2ray`] порт стоит **перед** типом адреса, а не после него, и тип
//! домена там `2`, а не `3` — то есть в записи SOCKS5 это номер IPv6.
//!
//! Отсюда решение: два кодировщика, а не один с флагом. Один с флагом
//! однажды запишет домен как IPv6, и найдётся это не на сборке, а в поле.
//!
//! Общее у них важнее различий: **домен передаётся доменом**. Разрешать его
//! здесь значило бы потерять имя ровно там, где оно единственное, что есть,
//! — правило «youtube.com в тоннель» работает только по имени, а после
//! разрешения от него остаётся адрес из CDN, общий с десятком других сайтов.

pub mod socks;
pub mod v2ray;
