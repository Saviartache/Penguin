//! Мультиплексор: сколько угодно потоков и датаграмм в одном соединении.
//!
//! ```text
//!  session   разбор кадров, очереди потоков, запись под общим замком
//!  stream    поток приложения: обычный AsyncRead + AsyncWrite
//!  datagram  датаграммный канал: адрес на каждой посылке
//! ```
//!
//! # Одна сессия на обе стороны
//!
//! Клиент и сервер разбирают одни и те же кадры, и второй такой разбор
//! разошёлся бы с первым на первом же исправлении. Различие между сторонами
//! ровно одно и выражено ролью: потоки открывает клиент, а сервер их
//! принимает. Всё остальное — очереди, дополнение, проверка живости,
//! смерть сессии — общее.

pub mod datagram;
pub mod session;
pub mod stream;

pub use datagram::PingwinDatagram;
pub use session::{DatagramRequest, Incoming, Role, Session, StreamRequest};
pub use stream::PingwinStream;
