//! Pingwin — свой протокол Penguin: рукопожатие в форме TLS 1.3, 0-RTT,
//! мультиплексор и обход DPI в первой посылке.
//!
//! ## Зачем ещё один протокол
//!
//! Двадцать с лишним протоколов в этом дереве написаны не нами, и каждый
//! тянет за собой свою историю. У одних опознание видно на проводе (VMess,
//! Shadowsocks), у других всё держится на настоящем TLS с настоящим
//! сертификатом (Trojan, NaiveProxy, TrustTunnel) — и тогда до первого
//! запроса проходит три оборота и виден весь набор расширений `rustls`.
//! Третьи прячутся хорошо (Reality), но требуют чужого сервера, чужого
//! клиента TLS и не умеют ни мультиплексирования, ни 0-RTT.
//!
//! Pingwin собран из того, что каждый из них делает правильно, и без того,
//! чем каждый из них платит:
//!
//! | Свойство                        | Как сделано                          |
//! | ------------------------------- | ------------------------------------ |
//! | на проводе — обычный TLS 1.3    | настоящий `ClientHello` браузера, дальше только записи данных |
//! | опознание не видно              | AEAD в `SessionID`, ключ — из X25519 с постоянным ключом сервера |
//! | активная проверка бесполезна    | не узнав клиента, сервер отдаёт соединение прикрытию |
//! | прямая секретность              | второй X25519, эфемерный с обеих сторон |
//! | первый запрос без оборотов      | 0-RTT: `OPEN` уезжает вместе с приветствием |
//! | повтор ранних данных невозможен | окно эфемерных ключей плюс отметка времени |
//! | одно соединение на всё          | мультиплексор: потоки, датаграммы, проверка живости |
//! | длины записей ничего не выдают  | расписание дополнения выведено из ключа, а не из таблицы |
//! | DPI режет соединение            | обход по мотивам `zapret2` в первой посылке |
//!
//! ## Устройство
//!
//! ```text
//! factory ──► outbound ──► handshake ──► mux::session ──┬─► mux::stream
//!                              │                        └─► mux::datagram
//!                              │
//!                          records  (запись: заголовок TLS + AEAD)
//!                              │
//!                            wire/   (формат: ключи, приветствия, кадры)
//!
//! link      ссылка-приглашение: профиль одной строкой (её собирает сервер)
//! ```
//!
//! Раздел [`wire`] — чистая логика без сокетов и ожидания, и он же общий с
//! сервером (`servers/pingwin`): формат провода, разобранный дважды, — это
//! два разных ответа на первый же неудобный вопрос.
//!
//! ## Как выглядит разговор
//!
//! ```text
//!  ──► [ложное приветствие]          только при обходе DPI, малый TTL
//!  ──► 16 03 01 ..  ClientHello      настоящий отпечаток браузера
//!  ──► 14 03 03 ..  ChangeCipherSpec
//!  ──► 17 03 03 ..  ранние данные    0-RTT: первый OPEN и первый запрос
//!  ◄── 16 03 03 ..  ServerHello
//!  ◄── 14 03 03 ..  ChangeCipherSpec
//!  ◄── 17 03 03 ..  записи данных
//!  ──► 17 03 03 ..  записи данных
//! ```
//!
//! После `ChangeCipherSpec` настоящий TLS 1.3 не показывает наружу ничего,
//! кроме записей данных, — и мы тоже. Отличить одно от другого по форме
//! потока нельзя, потому что формы больше нет.
//!
//! ## Чего здесь нет и почему
//!
//! - **Настоящего TLS.** Записи только выглядят как TLS: ни сертификата, ни
//!   `Finished`, ни списка шифров, которым можно договориться. Сервер
//!   опознаётся тем, что владеет закрытым ключом X25519, — этого достаточно
//!   и это дешевле целого рукопожатия.
//! - **Смены порта.** Соединение одно и живёт долго; смена порта имеет смысл
//!   там, где соединений много и каждое короткое.
//! - **`badsum`, `badseq`, `ipfrag` и прочего из `zapret2`.** Им нужен сырой
//!   сокет, а сокеты здесь выдаёт [`Dialer`](penguin_proto::dialer::Dialer)
//!   (`AGENTS.md` §3). Что осталось и почему — в документе
//!   [`penguin_transport::desync`].
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`],
//! [`penguin_transport`] и [`penguin_utls`] — крейтов своего уровня
//! (`AGENTS.md` §1.1, §1.1.1). Сокетов он не открывает: их выдаёт
//! `Dialer`, иначе рукопожатие ушло бы в собственный, ещё не поднятый
//! тоннель.

