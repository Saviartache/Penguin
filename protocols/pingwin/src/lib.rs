//! Pingwin — свой протокол Penguin поверх HTTP/3.
//!
//! На проводе — обычное соединение QUIC с сайтом: настоящий TLS 1.3,
//! настоящий сертификат, ALPN `h3`. HTTP/1.1 и HTTP/2 нет ни в какой роли.
//! Формат провода — `PROTOCOL.md` рядом.
//!
//! | Свойство                        | Как сделано                          |
//! | ------------------------------- | ------------------------------------ |
//! | на проводе — обычный HTTP/3     | QUIC v1, TLS 1.3, сертификат на имя сервера |
//! | сервер не подменить             | сертификат **и** доказательство ключом X25519 |
//! | повтор опознания бесполезен     | доказательство привязано к экспорту TLS соединения |
//! | активная проверка бесполезна    | чужому сервер отвечает статическим сайтом |
//! | одно соединение на всё          | потоки — `CONNECT`, UDP — датаграммы HTTP/3 |
//!
//! ## Устройство
//!
//! ```text
//! factory ──► outbound ──► session ──┬─► stream    поток CONNECT
//!                                    └─► datagram  канал connect-udp
//!
//! wire/   формат: ключи, опознание, датаграммы (общий с сервером)
//! link    ссылка-приглашение (её собирает сервер)
//! ```
//!
//! Раздел [`wire`] — чистая логика без сокетов и ожидания, и он же общий с
//! сервером (`servers/pingwin`).
//!
//! ## Чего здесь нет и почему
//!
//! - **Своего шифрования поверх QUIC.** Его даёт TLS 1.3 внутри QUIC; Pingwin
//!   добавляет только опознание.
//! - **0-RTT.** Соединение одно и живёт долго: экономия оборота на нём одном
//!   не окупает повтора ранних данных.
//! - **Смены порта.** Соединение одно и живёт долго.
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`] (`AGENTS.md` §1.1). Сокетов он не открывает: их
//! выдаёт `Dialer`, иначе рукопожатие ушло бы в собственный, ещё не поднятый
//! тоннель.

