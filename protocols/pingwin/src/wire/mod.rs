//! Формат провода: всё, что можно посчитать и проверить, ничего не отправляя.
//!
//! ```text
//!  keys     ключевое расписание: из двух Диффи-Хеллманов и пароля в ключи
//!  hello    первая посылка и ответ на неё в форме TLS 1.3
//!  record   запись на проводе: пять байт заголовка и AEAD внутри
//!  frame    кадр мультиплексора внутри записи
//!  padding  расписание дополнения, выведенное из ключа
//!  replay   окно повторов: сторона сервера, но логика чистая
//! ```
//!
//! Раздел общий для клиента и сервера — оба разбирают один и тот же формат, и
//! две его копии разошлись бы на первом же исправлении. Ни сокета, ни
//! ожидания здесь нет: всё это чистые функции над байтами, и тестируются они
//! без сети.

