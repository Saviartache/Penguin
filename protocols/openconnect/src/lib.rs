//! OpenConnect: протокол Cisco AnyConnect и `ocserv`, пакеты внутри TLS.
//!
//! Спецификации у протокола нет — он реконструирован сообществом. Эталон
//! здесь — исходники клиента `openconnect` (`cstp.c`, `auth.c`, `http.c`) и
//! сервера `ocserv` (`src/worker-http.c`, `src/worker-vpn.c`, `src/worker-auth.c`),
//! ветка `master` по состоянию на 2026-09-05. Все имена заголовков, форматы
//! кадров и константы ниже сверены с этими файлами; расхождения с другими
//! реализациями (Cisco ASA, GlobalProtect) не проверялись и не предполагаются.
//!
//! # Как это устроено
//!
//! ```text
//!  factory ──► auth::login ──► cstp::connect ──► cstp::CstpConnection (PacketOutbound)
//!               │                  │                    │
//!          POST + XML         CONNECT + заголовки   кадры STF внутри TLS
//!          (своё TLS-           X-CSTP-*             (новое TLS-соединение,
//!           соединение)                               отдельное от входа)
//! ```
//!
//! Опознание — это обмен HTTPS-запросами с телом XML (`config-auth`), а не
//! поле пароля: клиент шлёт форму, сервер присылает форму в ответ или
//! `id="success"`. Только после успеха открывается **второе**, отдельное
//! TLS-соединение с запросом `CONNECT /CSCOSSLC/tunnel`, и уже в его ответе
//! сервер называет адрес интерфейса, MTU, сроки `keepalive`/DPD — то есть
//! именно то, чем [`PacketInterface`](penguin_proto::packet::PacketInterface)
//! наполняется после подключения, а не из настроек профиля.
//!
//! # Чего здесь нет и почему
//!
//! **DTLS.** В `rustls` его нет — а значит, нет и датаграммного канала,
//! которым в оригинале передаются данные. Протокол при этом работает: весь
//! трафик идёт по CSTP поверх TCP (`cstp::frame`), — но это TCP поверх TCP со
//! всеми его бедами: потеря пакета на плохой линии превращается в остановку
//! всего потока, пока TCP-тоннель не подтвердит доставку. Заводить DTLS
//! вручную поверх `UdpSocket`, который выдаёт [`Dialer`](penguin_proto::dialer::Dialer),
//! — отдельная работа: свой рекорд-протокол, свой рукопожатие, свои шифры. Не
//! в этой фазе.
//!
//! **Второй фактор во время подключения.** У проекта нет ни одного протокола,
//! который спрашивает что-то *в процессе* установления соединения, и заводить
//! такой канал в интерфейсе — отдельная задача не этого крейта. Здесь
//! поддержано то, что работает без диалога: имя и пароль в один или два
//! обмена (`ocserv` иногда разносит их по разным формам — см.
//! [`auth`]). Если сервер запрашивает что-то третье — код одноразового
//! пароля, второй, отдельный пароль, — крейт возвращает
//! [`OpenConnectError::SecondFactorRequired`] с текстом подсказки поля, а не
//! притворяется, что подключился.
//!
//! **Сжатие.** `X-CSTP-Accept-Encoding` в запросе не посылается: без него
//! сервер не предложит `lzs`/`oc-lz4`/`deflate`, и разбирать кадр типа
//! `AC_PKT_COMPRESSED` не придётся вовсе. Дешёвая экономия трафика ценой ещё
//! одного формата кадра, который нечем проверить без стенда с ocserv под
//! рукой.
//!
//! **IPv4 обязателен.** [`PacketInterface::ipv4`](penguin_proto::packet::PacketInterface)
//! в контракте не `Option`: направление обязано его вернуть. Развёртывание
//! `ocserv` без пула IPv4 контрактом не поддержано; в этом случае
//! [`PacketFactory::build`](penguin_proto::packet::PacketFactory::build),
//! которую реализует [`factory::OpenConnectFactory`], вернёт понятную ошибку, а не
//! адрес `0.0.0.0`.
//!
//! # Устройство крейта
//!
//! ```text
//!  config   настройки: адрес, имя, пароль, TLS
//!  auth     HTTPS + XML: форма входа, ответ сервера, cookie `webvpn`
//!  cstp     CONNECT, заголовки X-CSTP-*, кадры, keepalive/DPD, направление
//!  error    OpenConnectError -> ProtocolError, по вариантам
//!  factory  PacketFactory: разбор параметров и сборка направления
//! ```
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

