//!
//! Здесь нет ни сокетов, ни `tokio` — чистые функции и типы без внутренней
//! изменяемости сверх собственного состояния шифра, которые проверяются без
//! сети и без ожидания. Асинхронное чтение и запись — в [`crate::stream`] и
//! [`crate::connector`].

