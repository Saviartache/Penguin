//! VMess: предшественник VLESS — шифрует сам, поверх любого транспорта.
//!
//! ## Что это за протокол
//!
//! В отличие от VLESS, у которого своего шифрования нет вовсе, VMess шифрует
//! заголовок и тело сам — исторически он появился раньше и был рассчитан на
//! то, чтобы работать без TLS снаружи. Платит он за это заметно бо́льшей
//! сложностью: заголовок опознаётся не паролем в открытом виде, а
//! шестнадцатью байтами, зашифрованными так, что перебрать пользователей
//! сервер может, а угадать заголовок по одному только виду пакета —
//! посторонний не может (см. [`crypto::auth_id`]).
//!
//! **Только AEAD-заголовок.** Старый вариант с `alterId > 0` (MD5-опознание,
//! чувствительное к рассинхронизации часов ещё сильнее, чем нынешнее) не
//! реализован и не будет: он снят с поддержки и у самого v2ray.
//! `alter_id > 0` в настройках — ошибка, а не тихое переключение на старый
//! режим ([`config::VmessConfig::validate`]).
//!
//! ## Устройство крейта
//!
//! ```text
//!  crypto   примитивы: вложенный KDF, опознаватель, шифр тела, `cmdKey`
//!  frame    формат кадра: заголовок запроса, заголовок ответа, тело
//!  config   настройки профиля и их проверка
//!  connector сокет, TLS, перенос, заголовок — как открыть поток до сервера
//!  stream   поток после заголовка: снять ответ, кадровать тело
//!  datagram канал UDP: по потоку на адресата, как у VLESS
//!  outbound, factory — регистрация в общем реестре протоколов
//! ```
//!
//! Раскладка файлов и приём с UDP через отдельный поток на адресата —
//! списаны с [`protocols/vless`](../penguin_vless/index.html): это ближайший
//! родственник, и отличается VMess от него ровно на собственное
//! шифрование.
//!
//! ## Расхождение часов
//!
//! Опознаватель заголовка несёт метку времени, и сервер отвергает её, если
//! она разошлась с его часами больше чем на 120 секунд. Разойтись это может
//! неотличимо от неверного UUID — оба случая сервер встречает одним и тем же
//! молчаливым закрытием соединения — поэтому текст [`error::VmessError::Disconnected`]
//! называет обе причины прямо, а не только одну из них.
//!
//! ## Чего здесь нет
//!
//! - **Опознавания по `alterId` (legacy).** См. выше.
//! - **Заверенной длины кадра** (`RequestOptionAuthenticatedLength`,
//!   бит `0x10`). Экспериментальный флаг самого эталона, выключенный там по
//!   умолчанию; клиент его не выставляет и не понимает, если бы сервер
//!   зачем-то настоял на нём в одностороннем порядке — такого сервера
//!   попросту не существует.
//! - **Переносов `grpc`, `h2`, `kcp`, `quic`.** Только `tcp`, `ws`,
//!   `httpupgrade` — как у VLESS.
//! - **Проверки о живой сервер.** Формат собран по чтению исходников
//!   `v2fly/v2ray-core`, а не проверен подключением к `xray`/`v2ray`: в этом
//!   окружении нет ни того, ни другого. Тесты — на записанных байтах и на
//!   опубликованном внешнем векторе KDF ([`crypto::kdf`]), а не на круговом
//!   прогоне «зашифровали — расшифровали сами собой»: он прошёл бы и при
//!   одинаковой ошибке в обе стороны.

