//! Кадры протокола.
//!
//! Три уровня, и их стоит различать. [`varint`] — общее с QUIC кодирование
//! чисел. [`tcp`] и [`udp`] — сами кадры. [`padding`] — случайное дополнение,
//! без которого длины кадров выдают прокси наблюдателю, даже когда содержимое
//! зашифровано.
//!
//! Ни один файл здесь не знает про QUIC, сокеты и время: кадр — это чистое
//! преобразование байт, и проверяется он на записанных байтах, без сети.

pub mod padding;
pub mod tcp;
pub mod udp;
pub mod varint;

pub use padding::Padding;
pub use tcp::TcpResponse;
pub use udp::UdpMessage;
