//! Hysteria 2: прокси поверх QUIC с маскировкой под HTTP/3.
//!
//! ## Что это за протокол
//!
//! Две идеи, из которых он состоит.
//!
//! **Маскировка.** Сервер Hysteria 2 — настоящий сервер HTTP/3. Пробник,
//! постучавшийся на порт без верного пароля, видит веб-сайт. Пропуском служит
//! заголовок `Hysteria-Auth`, а успехом — код 233, а не 200 (см. [`auth`]).
//!
//! **Скорость вместо вежливости.** Обычное управление перегрузкой считает
//! потерю признаком затора и сбрасывает темп. Там, где потери берутся не от
//! затора, это разрушительно. [`congestion::brutal`] держит заданную скорость
//! и при потерях шлёт **быстрее**, чтобы дошедшая скорость осталась той, что
//! задал пользователь.
//!
//! Сверху — необязательные слои: [`transport::obfs`] прячет узнаваемый вид
//! пакетов QUIC, [`transport::hop`] меняет порт по расписанию.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► client ──┬─► auth        аутентификация HTTP/3
//!                       ├─► session/tcp поток на прикладное соединение
//!                       ├─► session/udp датаграммы, разобранные по сессиям
//!                       └─► transport   QUIC, обфускация, смена порта
//!                            └─► congestion/brutal
//!  frame — разбор и сборка байт, ничего не знает об остальном
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`] и [`penguin_proto`]. Ни правил
//! маршрутизации, ни TUN, ни интерфейса он не видит — это и делает его
//! заменяемым.
//!
//! Сокетов крейт не открывает: их выдаёт [`penguin_proto::dialer::Dialer`].
//! Иначе пакеты к серверу ушли бы в собственный, ещё не поднятый тоннель, и
//! подключение не состоялось бы никогда.

