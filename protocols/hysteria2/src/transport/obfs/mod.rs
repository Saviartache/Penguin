//! Обфускатор как слой над UDP-сокетом.
//!
//! Слой лежит **под** QUIC: обрабатывается каждый исходящий и входящий пакет
//! целиком, включая заголовки QUIC. Именно это и требуется — без обфускации
//! заголовок QUIC читается наблюдателем открытым текстом, и по нему видно и
//! версию протокола, и границы соединений, и сам факт того, что это QUIC.
//!
//! Цена — потеря аппаратной сегментации (GSO/GRO): пакеты приходится трогать
//! по одному. Поэтому без обфускации сокет берётся обычный, quinn'овский,
//! со всеми его оптимизациями — см. [`crate::transport::quic`].

#[cfg(feature = "obfs-gecko")]
pub mod gecko;
#[cfg(feature = "obfs-salamander")]
pub mod salamander;

/// Преобразование пакета перед отправкой и после приёма.
///
/// Работает с буферами, а не с `Vec`: на горячем пути по пакету на каждые
/// полтора килобайта трафика, и аллокация на каждый из них была бы заметна.
pub trait Obfuscator: Send + Sync + std::fmt::Debug + 'static {
    /// Насколько обфускация удлиняет пакет.
    ///
    /// На эту величину уменьшается доступный QUIC размер датаграммы: иначе
    /// обфусцированный пакет перестанет помещаться в путевой MTU и будет
    /// дробиться маршрутизаторами.
    fn overhead(&self) -> usize;

    /// Обфусцирует `input` в `output`.
    ///
    /// Возвращает длину результата или `None`, если в `output` не хватило
    /// места. Паниковать нельзя: на этом пути держится всё соединение.
    fn obfuscate(&self, input: &[u8], output: &mut [u8]) -> Option<usize>;

    /// Снимает обфускацию на месте.
    ///
    /// Результат оказывается в начале того же буфера; возвращается его длина.
    /// На месте — потому что снятие только укорачивает пакет, и лишняя копия
    /// здесь не нужна.
    ///
    /// `None` — пакет не разбирается. Такое приходит постоянно: на открытый
    /// порт стучится кто попало, и это не ошибка, а обычный фон.
    fn deobfuscate(&self, buf: &mut [u8]) -> Option<usize>;
}
