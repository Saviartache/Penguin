//! Надстройка `protocol`: кадрирование поверх потокового шифра.
//!
//! ```text
//!  method      имя надстройки в настройках
//!  client_id   общий на выход счётчик соединений для auth_*
//!  auth_aes128 auth_aes128_md5 и auth_aes128_sha1 — общий код, разный хэш
//!  state       состояние на одно соединение, выбор варианта
//! ```
//!
//! В отличие от `obfs` (внешний вид пакета), `protocol` работает с открытым
//! текстом до шифра: считает метки подлинности, режет данные на кадры,
//! добавляет заголовок с меткой времени на новое соединение. `origin` не
//! делает ничего из этого — данные идут как есть, без рамок и без меток,
//! точно как у обычного Shadowsocks. Подробности и то, чего здесь нет
//! (`auth_sha1_v4`, `auth_chain_a`/`auth_chain_b`) — в документе крейта.

pub(crate) mod auth_aes128;
pub(crate) mod client_id;
pub mod method;
pub(crate) mod state;

pub use method::ProtocolMethod;
