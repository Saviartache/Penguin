//! Криптография протокола: метод, вывод ключа, сами шифры.
//!
//! ```text
//!  method  какой шифр и какой длины у него ключ и IV
//!  kdf     пароль -> главный ключ (EVP_BytesToKey)
//!  cipher  сами потоковые шифры, оба направления
//! ```
//!
//! IV здесь не выводится из пароля вовсе: на запись это случайные байты,
//! свои на каждое соединение (как соль у Shadowsocks), на чтение — то, что
//! первым прислал сервер. Подробности — в документе [`kdf`].
//!
//! Здесь нет ни сокетов, ни `tokio`: чистые вычисления, которые проверяются
//! без сети. **Ни один из этих шифров не заверяет данные** — это касается
//! всех, включая AES: CFB и CTR такие же потоковые режимы, как RC4, и правку
//! шифротекста по дороге ни один из них не заметит. Подробности и то, что из
//! этого следует для клиента, — в документе крейта ([`crate`]).

pub mod cipher;
pub mod kdf;
pub mod method;

pub use method::Method;
