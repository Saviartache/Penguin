//! ShadowsocksR: форк Shadowsocks с двумя слоями надстроек поверх
//! потокового шифра.
//!
//! ## Откуда мы знаем, как он устроен
//!
//! Официальной спецификации у SSR нет и не было: протокол — это то, что
//! делает код `breakwa11/shadowsocksr`, автора-одиночки, который в 2015 году
//! добавил поверх обычного Shadowsocks обфускацию и метки подлинности, а
//! потом исчез из проекта. Оригинальный репозиторий давно удалён; здесь
//! сверено по резервной копии сообщества, `shadowsocksr-backup/shadowsocksr`
//! (ветка `manyuser` — самая новая в этом бэкапе, только в ней вообще есть
//! `auth_*`), и по независимой переписи на C,
//! `shadowsocksr-backup/shadowsocksr-libev`. Готового `shadowsocksr-rust` с
//! полным протоколом (а не только клиентом-подключателем к чужому серверу)
//! в природе не нашлось — есть только реализации на Python, C, C# и Go,
//! ведущие себя как один и тот же протокол по построению, а не по общему
//! коду.
//!
//! Расхождений между источниками при чтении не нашлось: Python и C сходятся
//! в каждой константе, которая вошла в этот крейт. Там, где отличается
//! только эстетика (например, сколько случайных байт добавить в URL
//! `http_simple` — Python берёт `0..64`, C — `0..63`), выбор сделан
//! самостоятельно и не является частью договора с сервером: сервер ищет
//! `\r\n\r\n` и ему всё равно, сколько байт до него.
//!
//! ## Главное, что нужно знать перед использованием
//!
//! **Ни один из шифров SSR не заверяет данные.** RC4 и AES в режимах CFB и
//! CTR — потоковые шифры без метки подлинности: перевёрнутый бит на проводе
//! превращается в перевёрнутый бит на выходе, и ни клиент, ни сервер этого
//! не заметят сами по себе. Это отличает SSR от обычного Shadowsocks, где
//! разрешены только AEAD-методы (`penguin_shadowsocks::crypto::Method`) —
//! там подмену трафика заметит сам шифр. У SSR так исторически: протокол
//! старше повсеместного перехода на AEAD, и часть его надстроек (`auth_*`)
//! добавляет HMAC поверх шифра именно затем, чтобы дать хоть какую-то
//! защиту от подмены, — но это HMAC на четыре байта с ключом, зависящим от
//! счётчика пакетов, а не полноценная AEAD-метка. Форма профиля обязана
//! сказать об этом вслух, а не делать вид, что разницы с Shadowsocks нет.
//!
//! **Протокол мёртв.** Поддержка здесь — ради старых подписок, а не потому,
//! что кто-то заводит новые серверы на SSR. В плане клиента он стоит в
//! очереди низко и намеренно, а войдёт в сборку `full`, а не в `default`.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound ──► stream: obfs ─ шифр ─ protocol
//!  crypto     метод, вывод главного ключа, сами шифры
//!  obfs       внешний вид пакета: `plain`, `http_simple`
//!  protocol   кадрирование поверх шифра: `origin`, `auth_aes128_md5/sha1`
//! ```
//!
//! Направление шифрования и направление кадрирования — независимые оси:
//! любой шифр можно сочетать с любой парой `obfs`+`protocol`. Адрес
//! назначения кодируется тем же форматом SOCKS5, что и у Shadowsocks —
//! [`penguin_transport::addr::socks`], своей записи здесь нет.
//!
//! ## Что сделано
//!
//! - **Шифры:** `none`, `rc4-md5`, `aes-{128,192,256}-cfb`,
//!   `aes-{128,192,256}-ctr`.
//! - **obfs:** `plain` (без обфускации), `http_simple`
//!   (`http_simple_compatible` принимается тем же именем).
//! - **protocol:** `origin` (без кадрирования), `auth_aes128_md5`,
//!   `auth_aes128_sha1`.
//! - Только TCP. Только клиент (направление `Outbound`) — серверной стороны
//!   в проекте нет и не будет, она никому не нужна.
//!
//! ## Чего здесь нет
//!
//! - **Шифры** `table`, `salsa20`, `chacha20` и вариации CFB/OFB прежних
//!   версий OpenSSL (`bf-cfb`, `camellia-*-cfb`, `cast5-cfb`, `des-cfb`,
//!   `idea-cfb`, `rc2-cfb`, `seed-cfb`, `*-cfb1`, `*-cfb8`) — редкие в живых
//!   подписках; добавляются в [`crypto::method`] и [`crypto::cipher`] одной
//!   строкой в каждый, если понадобятся.
//! - **obfs** `http_post`, `random_head`, `tls1.2_ticket_auth` (полноценное
//!   поддельное рукопожатие TLS с разбором ответа сервера — самая дорогая
//!   часть `obfs`, сравнимая по объёму с `http_simple` и `plain` вместе).
//! - **protocol** `auth_sha1_v4`, `auth_chain_a`, `auth_chain_b`. Последние
//!   два — самая дорогая часть протокола: свой генератор случайных чисел,
//!   привязанный к ключу, и своё дополнение на каждый пакет; план явно
//!   откладывает их на конец очереди.
//! - **UDP.** У SSR он использует свои варианты кадрирования на каждый
//!   `obfs`/`protocol` (например, `auth_aes128_*` добавляет к датаграмме
//!   4 байта `uid` и HMAC), и без них включать `capabilities().udp` значило
//!   бы обещать то, что сразу же откажет.
//!
//! Незнакомое или нереализованное имя `obfs`/`protocol`/шифра
//! [`ShadowsocksrConfig::validate`] отклоняет с этим именем в тексте ошибки,
//! а не подставляет вместо него что-то похожее.

