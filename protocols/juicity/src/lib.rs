//! Juicity: QUIC без датаграмм, всё потоками.
//!
//! ## Что это за протокол
//!
//! Близкий родственник TUIC: то же опознание по UUID и паролю, тот же вывод
//! отпечатка из ключевого материала TLS. Различие в том, от чего Juicity
//! отказался: ни датаграмм QUIC, ни своих команд, ни сердцебиения. Соединение
//! несёт потоки, и всё едет потоками.
//!
//! Написан он ради UDP. У TUIC датаграммы идут либо датаграммами QUIC — и
//! тогда потерянный пакет виден приложению как молчание на несколько секунд,
//! потому что повторяет уже оно само, — либо каждая своим односторонним
//! потоком, и тогда на каждый запрос DNS заводится отдельный поток. Juicity
//! возит их одним потоком с надёжной доставкой.
//!
//! ## Что отсюда следует для клиента
//!
//! **Отказ сервер сообщает.** Не сойдясь отпечатком, он закрывает соединение
//! QUIC с кодом [`AUTH_FAILED`](link::AUTH_FAILED). Значит `AuthRejected`
//! здесь возвращать есть откуда — в отличие от Trojan и AnyTLS, где неверный
//! пароль неотличим от молчания.
//!
//! **Соединений бывает несколько.** У QUIC есть предел одновременных потоков,
//! и спецификация требует заводить новое соединение, когда он близко.
//! `quinn` оставшуюся ёмкость наружу не отдаёт, поэтому берётся прямо
//! разрешённый запасной путь: тридцать потоков на соединение (см. [`link`]).
//!
//! **Спецификация врёт про адрес.** В ней написано, что типы пронумерованы
//! `0`, `1`, `2`; и клиент, и сервер эталона пользуются нумерацией SOCKS5.
//! Подробности — в [`frame::proxy`].
//!
//! ## Устройство
//!
//! ```text
//!  factory ─► outbound ─► pool ──► link ──► опознание, счёт потоков
//!                          │
//!                          ├────► stream    поток приложения
//!                          └────► datagram  датаграммы одним потоком
//!  frame — разбор и сборка байт, без сети
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

