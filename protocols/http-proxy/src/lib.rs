//! Прокси HTTP CONNECT — в открытую (`http`) и под TLS (`https`).
//!
//! ## Что это за протокол
//!
//! Тот самый прокси, который умеет любой браузер и любая корпоративная сеть.
//! Клиент открывает соединение до прокси и пишет одну строку:
//!
//! ```text
//! CONNECT example.com:443 HTTP/1.1
//! Host: example.com:443
//! Proxy-Authorization: Basic ...
//! ```
//!
//! Прокси отвечает `200`, и дальше по тому же соединению идут байты
//! приложения как есть. Больше в протоколе ничего нет — ни UDP, ни
//! мультиплексирования.
//!
//! ## Почему протокола два
//!
//! Разница между `http` и `https` — ровно одна: во втором случае разговор с
//! **прокси** обёрнут в TLS. Дальше всё одинаково.
//!
//! Разделены они не для красоты. Прокси без TLS отдаёт по дороге всё, включая
//! адрес назначения в открытом виде и пароль в заголовке
//! `Proxy-Authorization` — тот кодируется base64, а это не шифрование.
//! Поэтому `http` уместен до прокси на этой же машине или в своей сети, а
//! наружу нужен `https`. Спрятать это в переключатель `tls: true` внутри
//! одного протокола значило бы, что разница видна только тому, кто открыл
//! файл настроек, — тогда как выбирают её в тот момент, когда добавляют
//! сервер.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound ──┬─► connect  запрос CONNECT и разбор ответа
//!                         ├─► tls      обёртка разговора с прокси
//!                         └─► basic    пароль в заголовке
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`] и [`penguin_proto`]. Сокетов он не
//! открывает: их выдаёт [`penguin_proto::dialer::Dialer`] — иначе пакеты к
//! прокси ушли бы в собственный, ещё не поднятый тоннель.

