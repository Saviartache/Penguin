//! GOST Relay: базовый протокол ретрансляции проекта `gost`.
//!
//! ## Откуда взят формат
//!
//! Открытого описания у протокола нет — `go-gost` документирует настройку
//! узлов, а не байты на проводе. Формат восстановлен по исходникам трёх
//! репозиториев организации `go-gost`:
//!
//! - `github.com/go-gost/relay` (сам формат кадра: `relay.go`, `feature.go`),
//!   ревизия `d323730` ветки `master` от 2026-07-24;
//! - `github.com/go-gost/x` (клиент и сервер обработчика `relay`:
//!   `connector/relay/*.go`, `handler/relay/*.go`), ревизия `fe9d9c9` ветки
//!   `master` от 2026-09-05;
//! - `github.com/go-gost/gosocks5` (запись `UDPHeader`, на которую ссылается
//!   `x` при описании настоящего `UDP ASSOCIATE`), ревизия `44f84c6` ветки
//!   `master` от 2026-07-13.
//!
//! Расхождений между источниками не нашлось — `x` реализует ровно то, что
//! описывает `relay`, — но один источник расходится сам с собой: комментарий
//! к `UserAuthFeature` в `feature.go` называет пароль в одной строке
//! обязательным («1 to 255» байт), а в соседней — необязательным («0 to 255,
//! 0 means no password»). Код `Encode`/`Decode` длину не проверяет вовсе,
//! поэтому здесь принято мнение кода: пустые имя и пароль разрешены
//! (подробности — [`frame::request`]).
//!
//! ## Устройство кадра
//!
//! Клиент шлёт заголовок запроса — версию, команду и список признаков
//! (`TYPE(1) LEN(2, BE) DATA` подряд, произвольным числом) — и получает в
//! ответ версию, статус и снова список признаков. Признак адреса назначения
//! использует ту же запись, что SOCKS5 (`ATYP`+`ADDR`+`PORT`), — она уже
//! есть в [`penguin_transport::addr::socks`], и здесь заведена не своя.
//! Подробности и байтовые тесты — в [`frame`].
//!
//! ## Что отсюда следует для клиента
//!
//! **Отказ по имени и паролю сервер сообщает явно.** Заголовок ответа несёт
//! статус, и `StatusUnauthorized` (`0x02`) — это ровно то, что отличает GOST
//! Relay от Trojan, VLESS и AnyTLS: там сервер, не узнавший клиента, либо
//! закрывает соединение молча, либо отдаёт трафик чужому сайту. Здесь есть
//! откуда взять [`error::GostRelayError::AuthRejected`], и `supervisor` не
//! станет долбиться повторно с заведомо неверным паролем.
//!
//! **У протокола самого по себе нет TLS.** `relay.go` вообще не упоминает
//! шифрование — предполагается, что его обеспечивает транспорт снизу.
//! Умолчание [`config::Security::None`] честно отражает это: включённый по
//! умолчанию TLS для протокола, в котором его нет, выглядел бы частью
//! протокола, а на самом деле был бы решением этого крейта.
//!
//! **Мультиплексирования нет.** `CmdConnect` не заводит сессию: каждое
//! новое соединение приложения — это новое TCP-соединение (или перенос
//! поверх него) до сервера со своим заголовком. Ровно как у SOCKS5, VLESS и
//! Trojan.
//!
//! ## UDP: почему не настоящий `UDP ASSOCIATE`
//!
//! У GOST Relay такой режим есть — `CmdBind` с флагом UDP, один поток
//! разбирает адресатов на каждой посылке, — но сервер включает его отдельной
//! настройкой (`x/handler/relay/metadata.go`, поле `enableBind`, по
//! умолчанию `false`): без неё запрос получает `StatusForbidden`.
//! Рассчитывать на настройку, которую подавляющее большинство серверов не
//! включает, значит называть проксированием то, что не заработает почти
//! нигде. Вместо этого используется `CmdConnect` с флагом UDP — тот же
//! режим, каким открывается TCP, но привязанный к одному адресату; канал
//! приложения держит по такому потоку на каждого адресата и разбирает, кто
//! ответил, сам. Подробности — в [`datagram`].
//!
//! ## Устройство крейта
//!
//! ```text
//!  factory ─► outbound ─► connector ─► сокет, TLS, перенос, заголовок
//!                          │
//!                          └────► datagram  по потоку на адресата UDP
//!  frame — разбор и сборка байт, без сети
//! ```
//!
//! ## Чего здесь нет
//!
//! **Режим `tunnel`.** Отдельная надстройка `go-gost` для регистрации узла
//! у релея (признаки `FeatureTunnel`, `FeatureMetadata`, свои `TunnelID` и
//! `ConnectorID`) — способ объединить несколько узлов в один вход, а не
//! способ выйти в сеть. Клиенту VPN она не нужна.
//!
//! **`CmdBind` как обработчик входящих (реверс-прокси).** Тот же режим, что
//! отвергнут выше для UDP, но для TCP: сервер слушает порт и пересылает
//! входящие соединения клиенту через мультиплексор. Нужен серверу, который
//! кто-то настраивает как точку входа, а не клиенту, который ищет выход.
//!
//! **gRPC и QUIC как перенос.** У `go-gost` они есть; здесь — только то, что
//! уже собрано в [`penguin_transport`]: голый поток, TLS, WebSocket,
//! `httpupgrade`.
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

