//! Reality: способ поднять VLESS под `ClientHello`, который выглядит как
//! настоящий браузер, а сервер отличает своих не сертификатом, а тем, что
//! умеет расшифровать `SessionID`.
//!
//! # Зачем это отдельно от обычного TLS
//!
//! Обычный TLS у VLESS ([`crate::config::Security::Tls`]) поднимается
//! `rustls` и проверяется сертификатом. Reality не может так: клиенту нужно
//! подменить `SessionID` в `ClientHello` и повторить отпечаток настоящего
//! браузера — `rustls` не даёт ни того, ни другого. Поэтому `ClientHello`
//! собирает `penguin-utls` ([`penguin_utls::Fingerprint`]), а рукопожатие
//! дальше ведёт этот модуль сам, без `rustls`.
//!
//! # Что здесь есть
//!
//! ```text
//!  config          настройки: публичный ключ сервера, short_id, server_name, отпечаток
//!  auth            данные опознания в SessionID, AuthKey, HMAC-проверка сертификата
//!  cipher_suite    три шифра TLS 1.3, из которых выбирает ServerHello
//!  key_schedule    RFC 8446 §7.1: Early/Handshake Secret, ключ и IV записи сервера
//!  record          расшифровка одной TLS-записи рукопожатия
//!  certificate     минимальный X.509 DER: ключ Ed25519 и подпись
//!  handshake       ведёт рукопожатие поверх готового потока, проверяет сервер
//! ```
//!
//! # Что здесь заканчивается
//!
//! [`handshake::verify`] доходит до `Certificate` сервера и проверяет его —
//! и на этом останавливается. `CertificateVerify` и `Finished` сервера не
//! разбираются, свой `Finished` не отправляется, прикладные ключи TLS 1.3 не
//! выводятся. **Соединение, прошедшее эту проверку, всё равно непригодно для
//! передачи байт VLESS** — для этого рукопожатие пришлось бы довести до
//! конца и завести поверх него запись/чтение прикладных данных, а поверх
//! этого — либо обычный TLS 1.3 (двойное шифрование поверх уже
//! зашифрованного VLESS-потока), либо XTLS Vision (`plan.md`, фаза 19,
//! второй пункт), которая как раз и существует, чтобы второго шифрования не
//! было. Ни то, ни другое этот шаг фазы не включает — см. отчёт о работе,
//! приложенный к коммиту.
//!
//! Отсюда прямое следствие для [`crate::config::VlessConfig`]:
//! `security = "reality"` в настройках сейчас проверяем (сервер либо
//! подтверждает себя, либо нет), но не соединяем — `connector.rs` отвечает
//! понятной ошибкой, а не притворяется работающим каналом.
//!
//! # Что нельзя проверить без живого сервера
//!
//! `key_schedule` и `record` сверены с RFC 8448 — официальными векторами TLS
//! 1.3 — байт в байт, а `certificate` — с примером `SubjectPublicKeyInfo` из
//! RFC 8410. Это TLS 1.3 сам по себе, не Reality.
//!
//! А вот весь `auth.rs` — формат данных опознания в `SessionID`, порядок
//! аргументов `HKDF`, то, что в HMAC идёт именно `subjectPublicKey`, а не
//! что-то ещё, — сверен только с исходниками `Xray-core` и `sing-box`
//! (совпадают между собой байт в байт, но это два потребителя одного и того
//! же неопубликованного формата, а не независимый источник истины). Ни
//! одного захвата настоящего рукопожатия Reality или официального тестового
//! вектора найти не удалось. Значит: **и то, что клиент посылает похожие на
//! правильные байты, и то, что сервер, который эти байты не примет,
//! промолчит, а не откажет, — можно доказать только подключением к живому
//! серверу Reality.** Ошибка в порядке `salt`/`info` `HKDF` или в позиции
//! `short_id` внутри данных опознания не покажет себя иначе, чем «сервер нас
//! не узнал» ([`error::RealityError::NotRecognized`]) — то есть точно так
//! же, как выглядело бы попадание на настоящий сайт.

