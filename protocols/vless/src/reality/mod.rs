//! Reality: способ поднять VLESS под `ClientHello`, который выглядит как
//! настоящий браузер, а сервер отличает своих не сертификатом, а тем, что
//! умеет расшифровать `SessionID`.
//!
//! # Зачем это отдельно от обычного TLS
//!
//! Обычный TLS у VLESS ([`crate::config::Security::Tls`]) поднимается
//! `rustls` и проверяется сертификатом. Reality не может так: клиенту нужно
//! подменить `SessionID` в `ClientHello` и повторить отпечаток настоящего
//! браузера — `rustls` не даёт ни того, ни другого. Поэтому `ClientHello`
//! собирает `penguin-utls` ([`penguin_utls::Fingerprint`]), а рукопожатие
//! дальше ведёт этот модуль сам, без `rustls`.
//!
//! # Что здесь есть
//!
//! ```text
//!  config          настройки: публичный ключ сервера, short_id, server_name, отпечаток
//!  auth            данные опознания в SessionID, AuthKey, HMAC-проверка сертификата
//!  cipher_suite    три шифра TLS 1.3, из которых выбирает ServerHello
//!  key_schedule    RFC 8446 §7.1 целиком: от Early Secret до прикладных ключей и Finished
//!  record          шифрование и расшифровка одной TLS-записи (рукопожатие и прикладные данные)
//!  certificate     минимальный X.509 DER: ключ Ed25519 и подпись
//!  handshake       ведёт рукопожатие поверх готового потока, проверяет сервер, доводит до конца
//!  application     слой прикладных записей TLS 1.3 — поверх него идут байты VLESS
//! ```
//!
//! # Что здесь сделано и что нет
//!
//! [`handshake::verify`] доходит до `Certificate` сервера, проверяет его и
//! останавливается — это дешёвая предварительная проверка
//! (`connector.rs::verify`), а не открытие канала.
//! [`handshake::connect`] ведёт то же самое рукопожатие до конца: разбирает
//! `CertificateVerify` (не проверяя её подпись отдельно — см. документ
//! `handshake.rs`, почему это безопасно) и `Finished` сервера, отправляет
//! свой `Finished`, выводит прикладные ключи TLS 1.3 (RFC 8446 §7.1) и
//! возвращает [`application::RealityStream`] — поток, поверх которого
//! `connector.rs` дальше отправляет заголовок VLESS, как поверх обычного
//! TLS.
//!
//! Не сделано и не будет частью этого шага:
//!
//! - **`KeyUpdate`** (RFC 8446 §4.6.3) — сервер, попросивший обновить ключи,
//!   обрывает канал ([`error::RealityError::KeyUpdateNotSupported`]), а не
//!   работает дальше на ключах, которые сервер уже считает устаревшими.
//! - **Возобновление сессии** (`NewSessionTicket`, PSK) — билеты нигде не
//!   сохраняются; кадр `NewSessionTicket` после `Finished` отбрасывается
//!   (`application.rs`), а не превращается в мусор на месте байт VLESS.
//! - **Двойное шифрование само по себе здесь не снимается.** VLESS идёт
//!   внутри уже зашифрованного TLS 1.3 — ровно так, как обычный
//!   `security = "tls"`. Второй слой снимает [`crate::vision`]
//!   (`flow = "xtls-rprx-vision"`), оборачивая [`application::RealityStream`]
//!   снаружи, — этот модуль сам по себе Vision не знает и не обязан.
//!
//! # Что нельзя проверить без живого сервера
//!
//! `key_schedule` и `record` сверены с RFC 8448 — официальными векторами TLS
//! 1.3 — байт в байт, включая прикладные ключи и `Finished` обеих сторон
//! (не только ключ записи сервера времён рукопожатия, как было раньше), а
//! `certificate` — с примером `SubjectPublicKeyInfo` из RFC 8410. Это TLS 1.3
//! сам по себе, не Reality, и годится ровно для того, чтобы доказать: с
//! настоящим сервером TLS 1.3 этот код говорит на одном языке.
//!
//! А вот **сама формула Reality — только прочитана**: раскладка данных
//! опознания в `SessionID`, порядок соли и метки `HKDF` при выводе
//! `AuthKey`, повторное использование этого ключа для `HMAC` (`auth.rs`) —
//! сверены только между `Xray-core` и `sing-box` (`auth.rs` — обе
//! независимые реализации совпадают байт в байт, но опубликованных векторов
//! для них не существует). Довести рукопожатие TLS 1.3 до конца не отвечает
//! на вопрос, который здесь на самом деле важен: узнал ли нас сервер как
//! Reality или мы просто достучались до обычного сайта, которому
//! непризнанный сервер молча пересылает `ClientHello`, — оба случая
//! заканчиваются одинаково успешным TLS 1.3 (сайт с этим тоже прекрасно
//! справляется). Единственное, что отличает эти случаи, — HMAC-проверка
//! сертификата в `auth.rs`, а её формат не имеет тестовых векторов. **«Канал
//! открылся и несёт байты» здесь ещё не значит «сервер нас узнал»** — это
//! можно доказать только подключением к живому серверу Reality с известным
//! ключом. Форма, где выбирают `security = "reality"`
//! (`crates/gui/src/forms/protocol/vless.rs`), обязана сказать это вслух.

