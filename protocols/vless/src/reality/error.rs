//! Ошибки рукопожатия Reality.
//!
//! Одно различие здесь важнее прочих: сервер, не узнавший клиента, не
//! присылает отказ — он либо молча пересылает `ClientHello` настоящему
//! сайту (и тот отвечает настоящим сертификатом), либо сам является таким
//! сайтом. С точки зрения этого клиента оба случая неотличимы от MITM,
//! подменившего сервер, и от собственной ошибки в `public_key`/`short_id`.
//! [`RealityError::NotRecognized`] говорит об этом прямо, а не изображает
//! «неверный пароль» — отличить эти случаи всё равно нельзя (см. `mod.rs`).

use thiserror::Error;

/// Что пошло не так при рукопожатии Reality.
#[derive(Debug, Error)]
pub enum RealityError {
    /// Настройки не разбираются или противоречивы.
    #[error("настройки Reality: {0}")]
    Config(String),

    /// Сервер прислал не TLS 1.3 или что-то, не похожее на `ServerHello`.
    #[error("ответ не по формату Reality: {0}")]
    Malformed(String),

    /// `ServerHello.key_share` — не `X25519`.
    ///
    /// Reality всегда требует эту группу: и `xray-core`, и `sing-box`
    /// принимают только `X25519`-ключ Reality в настройках сервера, а
    /// значит настоящий сервер Reality всегда ответит `X25519`. Другая
    /// группа означает: либо `HelloRetryRequest` (не поддержан, см.
    /// `handshake.rs`), либо это вовсе не Reality.
    #[error("ServerHello предложил группу {0:#06x} вместо X25519 — Reality с ней не работает")]
    UnexpectedGroup(u16),

    /// Сервер выбрал версию или шифр за пределами TLS 1.3.
    #[error("сервер согласился не на TLS 1.3: {0}")]
    UnsupportedNegotiation(String),

    /// Криптографическая операция отказала: `ring` не принял ключ или нонс,
    /// либо запись/данные опознания не расшифровались.
    ///
    /// В штатной работе почти не должно случаться — длины ключей и нонсов
    /// здесь фиксированы кодом, а не пришли снаружи, — кроме одного
    /// настоящего случая: запись рукопожатия испорчена или зашифрована не
    /// тем ключом (например, сервер выбрал не ту группу, а разбор этого не
    /// заметил раньше).
    #[error("криптографическая операция Reality отказала: {0}")]
    Crypto(&'static str),

    /// Сертификат сервера не разбирается как X.509 DER.
    #[error("сертификат сервера не разбирается: {0}")]
    Certificate(&'static str),

    /// Сервер не подтвердил себя как Reality.
    ///
    /// По построению неотличимо от того, что мы действительно достучались до
    /// обычного сайта (сервер нас не узнал и переслал `ClientHello` ему) или
    /// что канал подменён третьей стороной — Reality не даёт способа
    /// различить эти случаи, в этом и весь смысл маскировки (`mod.rs`).
    #[error(
        "сервер не подтвердил себя как Reality: либо `public_key`/`short_id` не подходят, \
         либо мы достучались до обычного сайта, либо канал кем-то подменён — отличить эти \
         случаи нельзя"
    )]
    NotRecognized,

    /// Ключевое расписание TLS 1.3 отказало — `ring` не принял длину вывода.
    ///
    /// В обычной работе не должно случаться: длины здесь все известны заранее
    /// и меньше любых ограничений `ring::hkdf`. Отдельный вариант — чтобы
    /// разбор не притворялся, будто это вернувшийся `Result` от сети.
    #[error("ключевое расписание TLS 1.3 отказало")]
    KeySchedule,

    /// `Finished` сервера не совпал с тем, что мы посчитали сами по тому же
    /// транскрипту (RFC 8446 §4.4.4).
    ///
    /// Отличается от [`Self::NotRecognized`]: до этого шага сертификат уже
    /// прошёл HMAC-проверку Reality, то есть сервер свой. Расхождение здесь
    /// означает подмену транскрипта на пути (или — вероятнее на практике —
    /// ошибку в этом коде: перепутанный порядок байт, не тот секрет,
    /// транскрипт не той длины) — не то, с чем можно молча смириться.
    #[error(
        "Finished сервера не совпал с посчитанным — транскрипт рукопожатия подменён или ключи разошлись"
    )]
    FinishedMismatch,

    /// Сервер запросил `KeyUpdate` (RFC 8446 §4.6.3) — не реализовано (см.
    /// документ модуля): канал закрывается, а не продолжает работать на
    /// ключах, которые сервер уже считает устаревшими.
    #[error("сервер запросил KeyUpdate — обновление ключей не реализовано, канал закрывается")]
    KeyUpdateNotSupported,

    /// Сервер прислал `alert` вместо прикладных данных.
    #[error("сервер прислал TLS alert (уровень {level:#04x}, описание {description:#04x})")]
    Alert {
        /// Байт уровня тревоги (`warning` = 1, `fatal` = 2).
        level: u8,
        /// Байт описания (RFC 8446 §6.2).
        description: u8,
    },

    /// Соединение оборвалось во время рукопожатия.
    #[error(transparent)]
    Io(#[from] std::io::Error),
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn not_recognized_names_all_three_indistinguishable_causes() {
        let text = RealityError::NotRecognized.to_string();
        assert!(text.contains("public_key"));
        assert!(text.contains("обычного сайта"));
        assert!(text.contains("подменён"));
    }
}
