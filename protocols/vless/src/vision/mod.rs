//! XTLS Vision (`flow = "xtls-rprx-vision"`) поверх Reality: конверт набивки
//! на первых пакетах, досмотр внутреннего TLS и, если он оказался TLS 1.3 с
//! приемлемым шифром, отказ от повторного шифрования — снятие второго слоя
//! «VLESS внутри TLS 1.3», о котором предупреждает [`crate::reality`].
//!
//! # Почему это лежит отдельно от `reality`
//!
//! Vision не про Reality саму по себе, а про байты **внутри** уже открытого
//! ей канала: он разбирает записи TLS на лету и, начиная с какого-то места,
//! отдаёт их поверх провода напрямую, в обход
//! [`RecordKey::seal`](crate::reality::record::RecordKey::seal)/
//! [`RecordKey::open`](crate::reality::record::RecordKey::open), которыми
//! обычно шифрует и расшифровывает каждую запись `RealityStream`.
//! Сделать это можно только владея записями внешнего TLS целиком — `rustls`
//! (`security = "tls"`) такого доступа не даёт, а собственный TLS 1.3
//! (`reality/{record,application,key_schedule,handshake}.rs`) даёт. Отсюда
//! и решение [`crate::config::VlessConfig::validate`]: `flow` принят только
//! при `security = "reality"`.
//!
//! # Что здесь есть
//!
//! ```text
//!  state    досмотр внутреннего TLS (XtlsFilterTls) — когда включать enable_xtls
//!  padding  конверт набивки одного блока (XtlsPadding/XtlsUnpadding)
//!  stream   VisionStream<S> — оборачивает RealityStream, ведёт оба направления
//! ```
//!
//! Сверено построчно с `XTLS/Xray-core`
//! (`github.com/XTLS/Xray-core`, ветка `main`, файлы
//! `proxy/vless/encoding/{addons.proto,encoding.go}` и `proxy/proxy.go` —
//! именно там, а не в `common/xtls/`, который этот эталон в актуальной
//! версии уже не содержит: код Vision переехал в пакет `proxy` целиком).
//!
//! # Что здесь сознательно не сделано
//!
//! - **Только Reality.** `security = "tls"` с `flow` отвергается
//!   `validate()` как ошибка настроек, а не тихо принимается без эффекта —
//!   у `rustls` нет способа ни писать готовую запись мимо шифрования, ни
//!   безопасно достучаться до буферов записи изнутри, которым эталон
//!   пользуется через `unsafe`/`reflect` в своём собственном `crypto/tls`.
//!   Хотеть Vision поверх обычного TLS осмысленно, реализовать его так же,
//!   как здесь, — нет.
//! - **Только `transport = "tcp"`.** Эталон прямо отказывается заводить
//!   Vision поверх чего-то, кроме `*tls.Conn`/`*reality.UConn` без переноса
//!   между ними и сырым сокетом (`XTLS only supports TLS and REALITY
//!   directly for now`, `proxy/vless/outbound/outbound.go`) — перенос
//!   `ws`/`httpupgrade` рвёт ту же прямую границу с внешним TLS, которая
//!   нужна для переключения.
//! - **Ни OS-splice, ни `unsafe`-доступ к чужим буферам.** У этой
//!   реализации собственный TLS 1.3, и переключение — это просто выбор
//!   между двумя методами уже владеемого типа (`RealityStream::io_mut`), а
//!   не разбор чужой раскладки памяти в обход системы типов.
//! - **Не проверено о живой сервер.** Как и вся Reality (см.
//!   [`crate::reality`]): всё, что здесь проверено, — это разбор конверта и
//!   условие переключения на записанных байтах (`state.rs`, `padding.rs`,
//!   `stream.rs`). «Канал переключился и несёт байты без второго слоя» на
//!   этих тестах ещё не значит «настоящий сервер Xray-core согласится вести
//!   себя так же» — совпадение с прочитанным исходником эталона здесь
//!   ровно того же качества, что и у остального Reality: сверено построчно,
//!   не прогнано через провод.
//! - **Меньше, чем в эталоне, но безопаснее, а не короче в ущерб
//!   корректности** — подробности у каждого упрощения в документе
//!   [`stream`].

