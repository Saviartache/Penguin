//! VLESS: опознание по UUID, а шифрует пусть транспорт.
//!
//! ## Что это за протокол
//!
//! Клиент шлёт версию, шестнадцать байт UUID, команду и адрес назначения — и
//! дальше по тому же соединению идут байты приложения. Своего шифрования нет
//! вовсе, и это не упущение, а решение: снизу и так TLS, а TLS внутри TLS
//! стоит заметно и ничего не добавляет.
//!
//! ## Что отсюда следует для клиента
//!
//! **Отказа нет.** Сервер, не узнавший UUID, закрывает соединение молча — как
//! и Trojan. Проверка при подъёме направления доходит до сертификата и на
//! этом останавливается.
//!
//! **Ответ приходит не сразу.** Свой заголовок сервер шлёт вместе с первыми
//! данными, а не в ответ на наш. Значит, прочитать его заранее нельзя:
//! соединение просто повисло бы. Снимает его [`stream`] при первом чтении.
//!
//! **Без TLS протокол голый.** `security = none` законен ровно тогда, когда
//! TLS снимает кто-то другой — сеть доставки перед сервером. Сам по себе он
//! означает, что UUID и адрес назначения идут по сети открытым текстом, и
//! журнал предупреждает об этом при каждом подключении.
//!
//! ## Две ловушки в записи адреса
//!
//! Порт стоит **перед** типом, а домен — это `2`, а не `3`; тройка означает
//! IPv6. В записи SOCKS5 всё наоборот, и общий кодировщик с флагом однажды
//! записал бы имя как адрес. Поэтому их два ([`penguin_transport::addr`]), и
//! на это есть отдельный тест.
//!
//! ## UDP
//!
//! Адрес назначения назван один раз, в заголовке, — значит, поток обслуживает
//! **одного** адресата. Канал датаграмм приложения держит по потоку на
//! каждого и разбирает, от кого пришёл ответ ([`datagram`]). У Trojan и
//! SOCKS5 этого нет: там адрес стоит на каждой посылке.
//!
//! ## Reality
//!
//! `security = "reality"` поднимает VLESS под `ClientHello`, отпечаток
//! которого повторяет настоящий браузер, а сервер отличает своих не
//! сертификатом, а тем, что умеет расшифровать `SessionID` (см. [`reality`]).
//! Проверка сервера доходит до его сертификата и на этом обрывается —
//! соединение, прошедшее её, ещё не готово нести байты VLESS: рукопожатие не
//! доведено до конца (подробности и то, чего не хватает, — в документе
//! [`reality`]).
//!
//! ## Чего здесь нет
//!
//! **Дополнения `xtls-rprx-vision`.** Оно требует разбора записей TLS на
//! лету и отказа от повторного шифрования после первых нескольких — этого
//! нет ни в Reality выше, ни в остальном VLESS. Принять его молча значит
//! подключаться не тем способом, о котором договорились с сервером, —
//! поэтому оно отвергается по имени, с объяснением.
//!
//! **gRPC как перенос.** Ждёт HTTP/2 в общем транспорте.

