//! TUIC v5: QUIC без своего шифрования поверх.
//!
//! ## Что это за протокол
//!
//! Ближайший родственник Hysteria 2: тот же QUIC, то же отсутствие
//! собственного шифрования — всё шифрует TLS внутри QUIC. Отличается тем, как
//! опознаёт своих и как носит датаграммы.
//!
//! ## Три вещи, которые здесь важны
//!
//! **Отпечаток привязан к соединению.** Тридцать два байта проверки
//! подлинности берутся экспортом ключевого материала того самого рукопожатия
//! TLS: меткой служит UUID, исходными данными — пароль. Подслушанный
//! отпечаток в другом соединении не подойдёт, а посчитать его заранее нельзя.
//!
//! Метка при этом — **шестнадцать сырых байт** UUID, а не его запись с
//! дефисами. Ошибиться легко, а выглядит ошибка как молчащий сервер.
//!
//! **Ответа нет ни на что.** Ни проверку подлинности, ни открытие потока
//! сервер не подтверждает: после `Connect` данные идут сразу. Значит, неверный
//! пароль виден только тем, что соединение закрылось.
//!
//! **Запись адреса третья в проекте.** Ни `socks`, ни `v2ray` не подходят:
//! здесь домен — это `0`, а IPv6 — `2`. Отдельный кодировщик с тестом,
//! который прямо проверяет, что все три записи расходятся ([`frame::address`]).
//!
//! ## Соединение одно на профиль
//!
//! В отличие от прокси-протоколов, здесь оно постоянное: рукопожатие QUIC и
//! проверка подлинности платятся **один раз**, а каждое прикладное соединение
//! — поток внутри уже установленного. Отсюда `multiplex: true`: маршрутизатор
//! вправе считать открытие потока дешёвым.
//!
//! Заново соединение крейт не поднимает. Оборвалось — направление отвечает
//! `Disconnected`, а поднимать профиль заново это дело `supervisor`, который
//! для того и существует. Свои повторы здесь означали бы вторую лестницу
//! ожидания рядом с той, что уже есть.
//!
//! ## Датаграммы
//!
//! Два режима, и выбор между ними не про скорость. `native` — датаграммами
//! QUIC: быстро и без порядка, то есть так, как UDP и устроен; датаграмма
//! длиннее путевого MTU при этом режется на части, потому что сама она не
//! собирается. `quic` — односторонними потоками: медленнее и с гарантией
//! доставки, которой у UDP быть не должно, зато проходит там, где датаграммы
//! QUIC режут по дороге.
//!
//! Сборка частей — общая с Hysteria 2 (`penguin_transport::frag`).
//!
//! ## Откуда взяты константы
//!
//! Из описания протокола (`EAimTY/tuic`, `SPEC.md`) и эталонной реализации
//! (`SagerNet/sing-quic`). По памяти здесь не написано ничего: ошибка в любой
//! из них выглядит одинаково — «сервер молчит».

