//! Trojan: поток внутри TLS, неотличимый от обращения к обычному сайту.
//!
//! ## Что это за протокол
//!
//! Клиент открывает обычное соединение TLS к серверу, шлёт 56 байт —
//! шестнадцатеричную запись SHA-224 от пароля, — потом адрес назначения, и
//! дальше по тому же соединению идут байты приложения. Своего шифрования у
//! Trojan нет вовсе: всё шифрует TLS, тот самый, которым пользуется браузер.
//!
//! Смысл протокола не в шифровании, а в **неотличимости**. Сервер, не узнавший
//! отпечаток пароля, не отвечает отказом: он пересылает пришедшие байты
//! настоящему веб-сайту, за который себя выдаёт. Тот, кто проверяет сервер
//! снаружи, видит сайт — потому что при любой ошибке сервер **и есть** этот
//! сайт.
//!
//! ## Что отсюда следует для клиента
//!
//! **Неверный пароль не отличить от верного.** Отказа не будет, `AuthRejected`
//! вернуть неоткуда. Проверка при подъёме направления доходит до сертификата
//! и на этом останавливается: дальше сервер молчит одинаково в обоих случаях.
//! Это не пробел реализации — это ровно то, ради чего протокол придуман.
//!
//! **Успех соединения с адресом назначения тоже не сообщается.** Ответа на
//! заголовок нет никакого, поэтому недостижимый адрес выглядит так же, как
//! неверный пароль: поток открылся и молчит.
//!
//! **Соединение на каждый поток.** Мультиплексирования нет; каждая вкладка
//! браузера платит своим рукопожатием TLS. Поэтому
//! [`Capabilities::multiplex`](penguin_proto::capabilities::Capabilities)
//! у него `false`: маршрутизатор не должен считать открытие потока дешёвым.
//!
//! **ALPN — часть маскировки.** Голый Trojan объявляет `h2, http/1.1`, как
//! браузер на обычном сайте. Пустой или свой ALPN выдал бы клиента первым же
//! пакетом рукопожатия, ещё до пароля.
//!
//! ## UDP
//!
//! Датаграммы идут **внутри того же потока TLS**: адрес и длина на каждой
//! посылке ([`frame::udp`]). Отдельного сокета, как у SOCKS5, здесь нет — и
//! в отличие от SOCKS5 под TLS, запросы DNS тоже защищены.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound ──┬─► frame::request  отпечаток, команда, адрес
//!                         └─► datagram        UDP поверх того же потока
//!  frame — разбор и сборка байт, ничего не знает об остальном
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

