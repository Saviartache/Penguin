//! SSH: клиент открывает каналы `direct-tcpip` — то же, что `ssh -D`, только
//! внутри клиента.
//!
//! ## Что это за протокол
//!
//! Мы становимся клиентом самого обычного сервера SSH и просим его открыть
//! `direct-tcpip`: канал, который сервер сам довозит до цели. Каждое
//! соединение приложения — отдельный канал внутри одного соединения SSH.
//! Никакого своего шифрования или формата кадров здесь нет: SSH — это не
//! обфускация под что-то ещё, а тот же протокол, которым ходят из терминала.
//!
//! ## Своей реализации SSH не будет
//!
//! Обмен ключами, шифры, опознание, каналы — отдельный проект, а не «ещё один
//! кадр» вроде тех, что разбирает `protocols/transport`. Эту работу делает
//! [`russh`] (чистый Rust, никакого `libssh`). Это самое крупное новое дерево
//! зависимостей среди протоколов клиента, и ненужные ему возможности
//! (сжатие, устаревшие и небезопасные алгоритмы, второй криптографический
//! бэкенд) выключены в `Cargo.toml` крейта.
//!
//! ## Отпечаток хоста обязателен
//!
//! SSH без проверки хоста — это тот же `insecure`, только молчаливый: любой,
//! кто перехватил соединение, становится «сервером». Поэтому поле отпечатка
//! в [`SshConfig`] обязательно, несовпадение — отдельная ошибка
//! ([`SshError::HostKeyMismatch`]), а принимается та запись, которая
//! оказывается на руках без лишнего шага: строка `ssh-keyscan`/`known_hosts`
//! или строка `ssh-keygen -l` (подробности — в [`fingerprint`]).
//!
//! ## Мультиплексирование настоящее
//!
//! Соединение SSH поднимается один раз, и каналы `direct-tcpip` живут в нём
//! все разом — считать их не нужно, в отличие от потоков QUIC у Juicity: у
//! `direct-tcpip` нет предела, который заставил бы завести второе соединение.
//! Умершее соединение поднимается заново при следующей попытке
//! ([`pool::SshPool`]).
//!
//! ## Устройство
//!
//! ```text
//!  factory ─► outbound ─► pool ──► session::Link ──► рукопожатие, отпечаток, опознание
//!                                       │
//!                                       └────► stream    канал приложения
//!  fingerprint — разбор и сверка отпечатка хоста, без сети
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`],
//! [`penguin_transport`] и [`russh`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

