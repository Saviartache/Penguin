//! Режим DPI: сервера нет, есть только обход.
//!
//! Если блокируют по имени (разбор `ClientHello`), а не по адресу, тоннель не нужен:
//! соединение идёт прямо к сайту, и меняется одно: первая посылка уходит по плану
//! ([`penguin_transport::desync`]), так что оборудование не собирает из неё имя узла.
//!
//! - Трафик не прячется: TLS приложения остаётся как был.
//! - Адрес не меняется: блокировку по адресу обход не лечит.
//! - UDP идёт как есть: обход режет поток TCP. QUIC браузер переживает откатом на TCP.
//! - Стратегий две: `multisplit` и `disorder`. `fake` и `fakedsplit` требуют ложной
//!   посылки, которую обычный сайт примет за разговор и оборвёт; настройки их отвергают.
//!
//! ```text
//!  factory ──► outbound ──┬─► flight     первая посылка по плану
//!                         └─► datagram   UDP как есть
//! ```
//!
//! Своих ошибок у крейта нет: настройки разбирает `transport`, остальное — сокет.

pub mod config;
pub mod datagram;
pub mod factory;
pub mod flight;
pub mod outbound;

pub use config::DpiConfig;
pub use factory::DpiFactory;
pub use outbound::DpiOutbound;

/// Имя протокола в настройках.
pub const PROTOCOL: &str = "dpi";
