//! Режим DPI: сервера нет, есть только обход.
//!
//! ## Зачем он нужен
//!
//! Блокировки бывают двух разных видов, и лечатся они по-разному.
//!
//! | Как заблокировано | Что видно | Чем лечится |
//! |---|---|---|
//! | по адресу: пакеты до сайта не доходят | соединение не устанавливается | только чужой адрес, то есть тоннель |
//! | по имени: соединение рвут, разобрав `ClientHello` | адрес отвечает, разговор обрывается | этого хватает |
//!
//! Второй случай — самый частый: оборудование провайдера читает имя узла в
//! первой посылке, находит его в списке и обрывает разговор. Сам сайт при
//! этом достижим. Тоннель здесь работает, но платится за него всем сразу:
//! сервером, деньгами, задержкой и тем, что весь трафик машины уезжает через
//! чужую страну.
//!
//! Этот режим не поднимает никакого тоннеля. Соединение идёт **прямо к
//! сайту**, и меняется в нём ровно одно: первая посылка приложения уходит не
//! одним куском, а по плану ([`penguin_transport::desync`]) — так, что
//! оборудование по дороге не собирает из неё имя узла.
//!
//! ## Что он не делает
//!
//! **Не прячет трафик.** Шифрования здесь нет — оно и не появлялось: между
//! приложением и сайтом остаётся то же TLS, что было. Адрес сайта провайдер
//! видит как видел.
//!
//! **Не меняет адрес.** Заблокированное по адресу останется заблокированным,
//! и с этим ничего не сделает никакой обход — нужен тоннель.
//!
//! **Не трогает UDP.** Датаграммы уходят как есть: обход, который здесь
//! сделан, — это разрез потока TCP, а в UDP потока нет. Заблокированный QUIC
//! браузер переживает сам — он возвращается на TCP, и вот там обход работает.
//!
//! ## Почему стратегий две, а не пять
//!
//! У обхода их пять, и три из них требуют **ложной посылки** — лишнего
//! приветствия, которое обязан пропустить сервер. У `pingwin` сервер свой и
//! пропустить умеет; здесь на том конце обычный сайт, и лишнее приветствие он
//! примет за начало разговора и оборвёт соединение сам.
//!
//! Поэтому `fake` и `fakedsplit` отвергаются разбором настроек, а не молча
//! превращаются в «ничего не делать»: стратегия, которая называется и не
//! делает того, что означает её имя, — худший вид настройки. Остаются
//! `multisplit` и `disorder` — ровно то подмножество, которое работает с
//! чужим, ничего о нас не знающим сервером.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound ──┬─► flight     первая посылка по плану
//!                         └─► datagram   UDP как есть
//! ```
//!
//! Своего перечисления ошибок у крейта нет: собственных отказов у него не
//! бывает вовсе. Настройки разбирает `transport` и он же о них сообщает,
//! остальное — ошибки сокета.
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`] (`AGENTS.md` §3).

