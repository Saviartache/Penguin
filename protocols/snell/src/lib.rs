//! Snell: протокол Surge, описания которого нет.
//!
//! ## Откуда мы знаем, как он устроен
//!
//! Ниоткуда официального. Surge закрыт, спецификации не публиковали ни разу.
//! Есть разбор, сделанный обратной разработкой сервера, и есть три сторонние
//! реализации, написанные по нему. Здесь стоит то, в чём они сходятся, а там,
//! где расходятся, — то, что говорит **код**, а не текст разбора: текст в
//! одном месте называет шифр, которого в коде тех же авторов нет.
//!
//! Отсюда правило для этого крейта: каждая константа, у которой был выбор,
//! помечена тем, откуда взята. Совместимость проверялась не с Surge — его у
//! нас нет, — а со сторонним сервером, который по тому же разбору написан.
//!
//! ## Версии
//!
//! Их пять, и они несовместимы: см. [`version`]. Версия — обязательное поле
//! без умолчания, потому что неверная не даёт отказа. Сервер расшифровывает
//! первый кусок другим шифром, видит мусор и молчит; человек в это время ищет
//! неисправность в сети.
//!
//! ## Что отсюда следует для клиента
//!
//! **Отказа по паролю нет.** Неверный PSK виден только тем, что не сошлась
//! метка подлинности, — то есть так же, как правка трафика по дороге. Общий
//! слой AEAD называет обе беды одним словом, и оно становится `AuthRejected`.
//!
//! **Ответ сервера приходит с задержкой.** Он шлётся, когда сервер соединился
//! с адресом назначения, поэтому снимается при первом чтении, а не при
//! открытии (см. [`stream`]). Отказ «не разрешается имя» приложение видит
//! ошибкой чтения.
//!
//! **Датаграмма — это кусок.** Длины внутри посылки нет; границу даёт кадр.
//! Значит канал датаграмм читается кусками, а не байтами (см. [`chunks`]).
//!
//! ## Устройство
//!
//! ```text
//!  factory ─► outbound ─► connector ─► сокет, обфускация, соль, заголовок
//!                          │
//!                          ├─► stream    поток приложения, ответ снимается лениво
//!                          └─► datagram  датаграммы: задача владеет потоком
//!  frame, version, crypto — разбор, таблицы и вывод ключа, без сети
//! ```
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает: их выдаёт
//! [`penguin_proto::dialer::Dialer`].

