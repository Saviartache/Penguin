//! MASQUE: `CONNECT-UDP` поверх HTTP/3 (RFC 9298).
//!
//! ## Источники
//!
//! Прочитан текст самих RFC, а не пересказы:
//!
//! - **RFC 9298** — «Proxying UDP in HTTP» (`CONNECT-UDP`): §2 (шаблон URI),
//!   §3 (запрос и ответ), §5 (кадр датаграммы UDP-проксирования).
//! - **RFC 9297** — «HTTP Datagrams and the Capsule Protocol»: §2.1
//!   (кадр `HTTP/3 DATAGRAM` и настройка `SETTINGS_H3_DATAGRAM`), §3.2
//!   (протокол капсул), §3.5 (капсула `DATAGRAM` и её равнозначность кадру).
//! - **RFC 9000**, §16 — переменной длины целое QUIC: формат и тестовые
//!   векторы для [`varint`].
//! - **RFC 9220** упомянут постольку, поскольку на него ссылается RFC 9298,
//!   §3.4, как источник настройки `SETTINGS_ENABLE_CONNECT_PROTOCOL` для
//!   HTTP/3 — самого текста RFC 9220 читать не понадобилось: используемая
//!   часть контракта («настройка должна быть подтверждена, прежде чем можно
//!   слать `:protocol`») целиком укладывается в то, что уже сказано в RFC 9298.
//! - **RFC 9484** — «Proxying IP in HTTP» (`CONNECT-IP`) — прочитан ради
//!   решения «делать или нет», см. ниже. Не реализован.
//!
//! ## Два режима одного протокола — и почему в клиенте только один
//!
//! MASQUE — это семейство: RFC 9298 даёт `CONNECT-UDP` (труба для
//! датаграмм с адресом на каждой посылке — точно то, что описывает
//! [`penguin_proto::datagram::ProxyDatagram`]), а RFC 9484 — `CONNECT-IP`
//! (труба для целых IP-пакетов — то, что описывает
//! [`penguin_proto::packet::PacketOutbound`]). Реализован только первый.
//!
//! Причина не в том, что `CONNECT-IP` сложнее в вакууме, а в том, что он
//! требует отдельного протокола согласования адреса: капсулы
//! `ADDRESS_ASSIGN`/`ADDRESS_REQUEST`/`ROUTE_ADVERTISEMENT` (RFC 9484, §4.7),
//! из которых `PacketInterface` (адрес, длина префикса, MTU) собирается уже
//! **после** подключения — тот же приём, что в плане назван для
//! OpenConnect (фаза 21). Это отдельная работа поверх и без того нового
//! `varint`/`capsule` фундамента, а не расширение уже написанного `Session`:
//! `CONNECT-IP` не открывает несколько каналов на разные цели, как
//! `CONNECT-UDP` (одна труба — весь трафик), значит `Session`, `Flow` и
//! `MasqueDatagram` этой фазы ему бы не подошли и наполовину. Сделать его
//! наспех, разделяя код с `CONNECT-UDP` там, где он на самом деле не общий,
//! означало бы то, от чего предостерегает `plan.md`: две половины вместо
//! одной цельной. Поэтому здесь — только `CONNECT-UDP`, сказано вслух, а не
//! молча.
//!
//! ## Согласование датаграмм HTTP/3 — и почему клиент их не просит
//!
//! RFC 9297, §2.1.1 требует, чтобы обе стороны прислали
//! `SETTINGS_H3_DATAGRAM = 1`, прежде чем кто-то из них отправит кадр
//! `HTTP/3 DATAGRAM` поверх QUIC. Без этого подтверждения — молчания или
//! отказа — датаграмма всё равно может быть передана: RFC 9297, §3.5
//! объявляет капсулу `DATAGRAM` семантически равной кадру, только надёжной
//! и по порядку, ценой задержки на голове очереди (head-of-line blocking) —
//! то самое замедление, о котором говорит `plan.md`.
//!
//! `h3` версии `0.0.8` умеет объявить эту настройку
//! (`Builder::enable_datagram`) и прочитать, подтвердил ли её собеседник
//! (`ConnectionState::settings().enable_datagram()`) — проверено по
//! исходникам крейта, не по документации. Чего он **не умеет** — так это
//! отдать наружу номер потока, которым помечается каждый кадр `HTTP/3
//! DATAGRAM` (RFC 9297, §2.1: «Quarter Stream ID» — номер потока, делённый
//! на четыре). Без этого номера кадр, пришедший по общему QUIC-соединению,
//! нечем сопоставить с открывшим его каналом `CONNECT-UDP` — а у одного
//! направления MASQUE их может быть много одновременно (см.
//! [`datagram`]).
//!
//! Поэтому этот клиент **сам не объявляет** `SETTINGS_H3_DATAGRAM` — то
//! есть заранее лишает прокси возможности слать ему настоящие кадры
//! `HTTP/3 DATAGRAM`, и сам их не шлёт, вместо того чтобы объявить умение,
//! которого на самом деле нет, и полагаться на непубличный порядок выдачи
//! номеров потоков в `quinn`. Если сервер поддерживает быстрый путь, а
//! клиент — нет, RFC 9297 не считает это отказом: обе стороны просто
//! используют капсулы, как если бы быстрый путь не существовал вовсе.
//! Разница с обычным «сервер не подтвердил» ровно та, о какой предупреждает
//! `plan.md`: без выделенного лога это было бы **не заметно снаружи** —
//! CONNECT-UDP работает, просто на потоке, а не на датаграммах, — поэтому
//! это названо здесь текстом, а не спрятано в поведении. Подробности — в
//! документации [`flow`] и [`transport`].
//!
//! Расширенный CONNECT (`SETTINGS_ENABLE_CONNECT_PROTOCOL`, RFC 9220) по RFC
//! 9298, §3.4 тоже требует подтверждения прокси прежде, чем клиент пошлёт
//! запрос с `:protocol: connect-udp`, — но проверить его заранее этот крейт
//! тоже не может, и снова из-за границ публичного API `h3`: чтение настроек
//! собеседника спрятано за фичой, предназначенной для авторов чужих
//! QUIC-бэкендов, а не для протоколов поверх `h3-quinn` (подробности — в
//! документации [`transport`]). Здесь это менее рискованно, чем с
//! датаграммами: RFC 9298 без этой настройки вообще не работает, так что
//! почти любой сервер, отвечающий на пути `/.well-known/masque/udp/…`, её
//! уже подтверждает. Клиент просто отправляет запрос — а если прокси
//! всё-таки не поддерживает расширенный CONNECT, это придёт как обычная
//! ошибка открытия канала (обрыв потока или всего соединения), а не как
//! отдельно пойманная причина.
//!
//! ## Сверка
//!
//! - [`varint`] сверен по тестовым векторам RFC 9000, §16 — они приведены в
//!   тексте самого RFC.
//! - [`capsule`] и [`request`] сверены по формату из RFC 9297/9298 построчно
//!   (см. документацию каждого модуля); отдельных тестовых векторов для
//!   капсул и запроса `CONNECT-UDP` ни в одном из RFC нет — сверки по
//!   готовым байтам для них не существует, и это не скрывается.
//! - Против живого сервера MASQUE (RFC 9298) не проверялось — это работа
//!   `scripts/interop`, вне границы этой фазы.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound ──► session ──┬─► transport (QUIC + рукопожатие h3)
//!                             │        │
//!                             │        └─► request (запрос CONNECT-UDP, разбор ответа)
//!                             │
//!                             └─► datagram (кэш адрес → канал) ──► flow (капсулы DATAGRAM)
//!                                                                       │
//!                                                                       └─► capsule + varint
//! ```
//!
//! `capsule` и `varint` не знают ни про `h3`, ни про `quinn` — это чистый
//! разбор байтов, тестируемый без сети (`AGENTS.md`, правило 2.3).
//!
//! ## Границы
//!
//! Крейт зависит только от [`penguin_core`], [`penguin_proto`] и
//! [`penguin_transport`]. Сокетов он не открывает — их выдаёт
//! [`penguin_proto::dialer::Dialer`], иначе рукопожатие ушло бы в
//! собственный, ещё не поднятый тоннель.

