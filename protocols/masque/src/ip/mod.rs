//! `CONNECT-IP` (RFC 9484): труба для целых IP-пакетов, одна на весь профиль.
//!
//! Другое устройство, а не второй транспорт [`crate`]'s CONNECT-UDP:
//! [`penguin_proto::packet::PacketOutbound`] вместо
//! [`penguin_proto::outbound::Outbound`], один поток на всё направление
//! вместо кэша каналов [`crate::datagram::MasqueDatagram`] по адресу
//! назначения. Ничего из `session`/`flow`/`datagram`/`transport` этого
//! крейта здесь не переиспользуется: то разделяемое, что там есть
//! (мультиплексор HTTP/3 поверх одного соединения на много целей),
//! `CONNECT-IP` не делает вовсе — у него ровно один поток, и делить нечего.
//!
//! # Почему HTTP/1.1 `Upgrade`, а не расширенный CONNECT у HTTP/2 или HTTP/3
//!
//! RFC 9484 определяет запрос двумя равноценными способами: HTTP/1.1
//! `Upgrade` (§4.2—4.3) и расширенный CONNECT у HTTP/2 или HTTP/3 (§4.4—4.5).
//! Оба заканчиваются одним и тем же — протоколом капсул (RFC 9297, §3.2) —
//! и сам документ не отдаёт предпочтения ни одному.
//!
//! Здесь выбран **первый**, и вот почему. Расширенный CONNECT у HTTP/2/3
//! требует псевдозаголовка `:protocol: connect-ip`. У `h3` версии `0.0.8`
//! (той, что в дереве, и она же последняя опубликованная версия на
//! `crates.io` на дату написания — новее просто нет) значение этого
//! псевдозаголовка отдаётся типом [`h3::ext::Protocol`] — закрытым
//! перечислением без публичного конструктора из строки. Проверено по
//! исходникам крейта (`h3-0.0.8/src/ext.rs`), а не по документации: у
//! `Protocol` есть ровно две именованные константы, `WEB_TRANSPORT` и
//! `CONNECT_UDP` (ею уже пользуется CONNECT-UDP этого же крейта, см.
//! [`crate::request`]), и `FromStr`, принимающий только строки
//! `"webtransport"`/`"connect-udp"`. Построить значение, которое
//! сериализуется в `"connect-ip"`, снаружи крейта `h3` нельзя никак — это не
//! ограничение видимости за фичой, как у датаграмм (см. документ [`crate`]),
//! а полностью закрытый тип без лазейки. Версия `h3` с
//! `Protocol::CONNECT_IP` существует только в неопубликованном состоянии
//! репозитория на GitHub; тянуть протокол через git-зависимость мимо
//! `crates.io` — тянуть непроверенный, незакреплённый код в рукопожатие
//! соединения, которое должно жить годами, ради одной константы. Это не
//! решается тем же приёмом, что у `SETTINGS_H3_DATAGRAM` (просто не
//! использовать возможность): здесь нет возможности, которую можно не
//! использовать, — этой версией `h3` нельзя отправить такой запрос вообще,
//! ни с датаграммами, ни без них.
//!
//! RFC 9484, §4.2—4.3 даёт полностью рабочую замену: тот же протокол капсул
//! поверх обычного `GET` с `Upgrade: connect-ip` и кодом ответа `101`, без
//! HTTP/3 и без `h3` вообще — TLS поверх TCP через тот же
//! [`Dialer`](penguin_proto::dialer::Dialer), которым пользуется
//! `penguin_openconnect`. Цена — то, чем в этом же крейте уже платит
//! CONNECT-UDP: нет мультиплексирования нескольких потоков в одном
//! соединении. Но CONNECT-IP открывает только один поток на весь профиль, и
//! мультиплексировать здесь и так нечего.
//!
//! # Согласование адреса
//!
//! Сразу после успешного апгрейда клиент посылает капсулу `ADDRESS_REQUEST`
//! (RFC 9484, §4.7.2) на IPv4 и IPv6 без предпочтения конкретного адреса и
//! ждёт `ADDRESS_ASSIGN` (§4.7.1) — см. модуль `negotiate`. Сервер, не приславший
//! адрес IPv4, — это понятная ошибка, а не интерфейс с нулевым адресом:
//! `PacketInterface::ipv4` обязателен по контракту, ровно как у OpenConnect.
//!
//! Капсулы `ROUTE_ADVERTISEMENT` (§4.7.3) разбираются и попадают в журнал, но
//! не меняют поведение направления: маршрутизация в этом клиенте — дело
//! профиля и `router`, а не протокола, и в
//! [`PacketInterface`](penguin_proto::packet::PacketInterface) нет поля под
//! маршруты (только адрес, MTU и DNS).
//!
//! # MTU
//!
//! RFC 9484 не определяет способа сервера назвать MTU тоннеля — ни аналога
//! `X-CSTP-MTU` у OpenConnect, ни капсулы под это. Используемое значение
//! (см. `outbound::INTERFACE_MTU`) взято не наугад: RFC 9484, §7.2 требует,
//! чтобы звено, переносящее IPv6, было не меньше 1280 байт, — это и есть
//! floor из самого документа, а не измеренный путь.
//!
//! # DNS
//!
//! RFC 9484 не даёт способа назвать сервер имён внутри тоннеля — ни один из
//! документа не упоминает такого механизма, в отличие от `X-CSTP-DNS` у
//! OpenConnect. [`PacketInterface::dns`](penguin_proto::packet::PacketInterface::dns)
//! у CONNECT-IP всегда пуст: доменные имена через это направление честно не
//! разрешаются, а не уходят мимо тоннеля молча.

