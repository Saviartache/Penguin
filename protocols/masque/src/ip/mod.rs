//! `CONNECT-IP` (RFC 9484): труба для целых IP-пакетов, одна на весь профиль.
//!
//! Другое устройство, а не второй транспорт [`crate`]'s CONNECT-UDP:
//! [`penguin_proto::packet::PacketOutbound`] вместо
//! [`penguin_proto::outbound::Outbound`], один поток на всё направление
//! вместо кэша каналов [`crate::datagram::MasqueDatagram`] по адресу
//! назначения. Ничего из `session`/`flow`/`datagram`/`transport` этого
//! крейта здесь не переиспользуется: то разделяемое, что там есть
//! (мультиплексор HTTP/3 поверх одного соединения на много целей),
//! `CONNECT-IP` не делает вовсе — у него ровно один поток, и делить нечего.
//!
//! # Перенос — только HTTP/3
//!
//! RFC 9484 даёт три способа: HTTP/1.1 `Upgrade` (§4.2—4.3) и расширенный
//! CONNECT у HTTP/2 или HTTP/3 (§4.4—4.5). Здесь — HTTP/3: `:protocol:
//! connect-ip` поверх своего HTTP/3 ([`penguin_transport::h3`]); прокси
//! обязан объявить расширенный `CONNECT`, иначе запрос не уйдёт. HTTP/1.1
//! клиент не говорит нигде.
//!
//! IP-пакеты ходят капсулами `DATAGRAM` по потоку, а не датаграммами
//! HTTP/3: поток один на весь профиль, и капсулы ему хватает. Датаграммы
//! клиент не объявляет, и сервер обязан отвечать капсулами же.
//!
//! # Согласование адреса
//!
//! Сразу после открытия потока клиент посылает капсулу `ADDRESS_REQUEST`
//! (RFC 9484, §4.7.2) на IPv4 и IPv6 без предпочтения конкретного адреса и
//! ждёт `ADDRESS_ASSIGN` (§4.7.1) — см. модуль `negotiate`. Сервер, не приславший
//! адрес IPv4, — это понятная ошибка, а не интерфейс с нулевым адресом:
//! `PacketInterface::ipv4` обязателен по контракту.
//!
//! Капсулы `ROUTE_ADVERTISEMENT` (§4.7.3) разбираются и попадают в журнал, но
//! не меняют поведение направления: маршрутизация в этом клиенте — дело
//! профиля и `router`, а не протокола, и в
//! [`PacketInterface`](penguin_proto::packet::PacketInterface) нет поля под
//! маршруты (только адрес, MTU и DNS).
//!
//! # MTU
//!
//! RFC 9484 не определяет способа сервера назвать MTU тоннеля — ни
//! заголовка, ни капсулы под это. Используемое значение
//! (см. `outbound::INTERFACE_MTU`) взято не наугад: RFC 9484, §7.2 требует,
//! чтобы звено, переносящее IPv6, было не меньше 1280 байт, — это и есть
//! floor из самого документа, а не измеренный путь.
//!
//! # DNS
//!
//! RFC 9484 не даёт способа назвать сервер имён внутри тоннеля.
//! [`PacketInterface::dns`](penguin_proto::packet::PacketInterface::dns)
//! у CONNECT-IP всегда пуст: доменные имена через это направление честно не
//! разрешаются, а не уходят мимо тоннеля молча.

