//! Shadowsocks: поток, зашифрованный целиком, без единого заголовка снаружи.
//!
//! ## Что это за протокол
//!
//! Клиент бросает случайную соль, выводит из неё и пароля сеансовый ключ и
//! дальше шлёт всё под ним: сначала адрес назначения, потом байты приложения.
//! Никакого рукопожатия, никакого ответа сервера, никаких полей в открытую —
//! снаружи виден поток случайных байт, начинающийся с соли.
//!
//! ## Что отсюда следует для клиента
//!
//! **Отказа не бывает.** Сервер, у которого другой пароль, не может даже
//! прочитать наш первый кусок — он просто закрывает соединение. Со стороны
//! клиента неверный пароль выглядит как не сошедшаяся метка подлинности, и
//! именно так он и сообщается: `AuthRejected`, повторять бессмысленно.
//!
//! **Подтверждения соединения тоже нет.** Как и у Trojan, недостижимый адрес
//! назначения выглядит молчанием: сервер про это ничего не говорит.
//!
//! **Соединение на каждый поток.** Мультиплексирования нет; каждое
//! подключение — своя соль и свой сеансовый ключ.
//!
//! ## Чего здесь нет
//!
//! **Потоковых шифров** (`aes-256-cfb`, `rc4-md5`). Они не заверяют данные:
//! правку по дороге не заметит ни клиент, ни сервер. Метод, который выглядит
//! как «ещё один в списке», а на деле снимает защиту целиком, в списке стоять
//! не должен.
//!
//! **Внешних плагинов** (`obfs-local`, `v2ray-plugin` отдельным процессом).
//! Запуск процессов протоколу не принадлежит — сокеты ему выдаёт
//! [`penguin_proto::dialer::Dialer`], и процессы выдавать было бы некому.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound ──┬─► stream    поток: соль, длина, кусок
//!                         └─► datagram  UDP: соль на каждой посылке
//!  crypto — метод, вывод ключей, шифрование куска
//! ```

