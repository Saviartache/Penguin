//! Shadowsocks: поток, зашифрованный целиком, без единого заголовка снаружи.
//!
//! ## Что это за протокол
//!
//! Клиент бросает случайную соль, выводит из неё и пароля сеансовый ключ и
//! дальше шлёт всё под ним: сначала адрес назначения, потом байты приложения.
//! Никакого рукопожатия, никакого ответа сервера, никаких полей в открытую —
//! снаружи виден поток случайных байт, начинающийся с соли.
//!
//! ## Что отсюда следует для клиента
//!
//! **Отказа не бывает.** Сервер, у которого другой пароль, не может даже
//! прочитать наш первый кусок — он просто закрывает соединение. Со стороны
//! клиента неверный пароль выглядит как не сошедшаяся метка подлинности, и
//! именно так он и сообщается: `AuthRejected`, повторять бессмысленно.
//!
//! **Подтверждения соединения тоже нет.** Как и у Trojan, недостижимый адрес
//! назначения выглядит молчанием: сервер про это ничего не говорит.
//!
//! **Соединение на каждый поток.** Мультиплексирования нет; каждое
//! подключение — своя соль и свой сеансовый ключ.
//!
//! ## Чего здесь нет
//!
//! **Потоковых шифров** (`aes-256-cfb`, `rc4-md5`). Они не заверяют данные:
//! правку по дороге не заметит ни клиент, ни сервер. Метод, который выглядит
//! как «ещё один в списке», а на деле снимает защиту целиком, в списке стоять
//! не должен.
//!
//! **Внешних плагинов** (`obfs-local`, `v2ray-plugin` отдельным процессом).
//! Запуск процессов протоколу не принадлежит — сокеты ему выдаёт
//! [`penguin_proto::dialer::Dialer`], и процессы выдавать было бы некому.
//!
//! ## Устройство
//!
//! ```text
//!  factory ──► outbound ──┬─► stream    AEAD: соль, длина, кусок
//!                         ├─► datagram  AEAD: соль на каждой посылке
//!                         ├─► tcp2022   2022: заголовок с меткой времени
//!                         └─► udp2022   2022: идентификатор сессии, счётчик
//!  crypto — метод AEAD, вывод ключей, шифрование куска
//!  method, kdf2022, header2022 — метод 2022, его вывод ключа, общий заголовок
//! ```
//!
//! ## AEAD 2022
//!
//! Три метода `2022-blake3-*` встали рядом с AEAD, а не поверх него: ключ
//! там — не пароль, а закодированный в base64 предварительный общий ключ
//! (PSK) ровно нужной длины (проверяется в
//! [`ShadowsocksConfig::validate`]), вывод сеансового ключа — BLAKE3
//! ([`kdf2022`]), а заголовки — свои, с меткой времени и антиреплей-полями
//! ([`tcp2022`], [`udp2022`]). Подробности и то, с чем сверена раскладка
//! байт, — в документах этих модулей.
//!
//! Сервер отвергает метку времени старше тридцати секунд
//! ([`header2022::check_timestamp`]): расхождение часов этой машины и
//! сервера выглядит как «сервер молчит», и текст ошибки
//! ([`error::ShadowsocksError::ClockSkew`]) называет это прямо, а не оставляет
//! искать в сети.
//!
//! **Раскладка байт сверена по двум независимым источникам** — `shadowsocks/
//! shadowsocks-crypto` (`v0.8.0`; сам крейт `shadowsocks-rust` больше не
//! хранит эту логику у себя, вынес в отдельный репозиторий) вместе с
//! `shadowsocks/shadowsocks-rust` (`v1.25.0`, откуда взят порядок полей на
//! проводе — `relay/tcprelay/aead_2022.rs`, `relay/udprelay/aead_2022.rs`,
//! `relay/tcprelay/proxy_stream/{client.rs,protocol/v2.rs}`) — и независимо
//! `SagerNet/sing-shadowsocks2` (`dev`, тот самый крейт, на который в
//! `sing-box` ссылается протокол `shadowsocks`, а не сам `sing-box`):
//! контекст BLAKE3, порядок полей TCP и UDP, нонс AES-GCM (байты 4..16
//! заголовка), явный нонс `XChaCha20` у UDP-ChaCha и лимит дополнения в 900
//! байт совпали у обоих дословно.
//!
//! **Упрощено против эталона, сознательно:**
//!
//! - **Расширенные заголовки личности (EIH)** — многопользовательские
//!   серверы (несколько PSK на одном порту) не поддержаны: конфигурация несёт
//!   ровно один ключ, а EIH — это то, чем клиент представляется одним из
//!   нескольких. Один PSK такого представления не требует.
//! - **Окно антиреплея и кеш смены сессии собеседника** (UDP) — это защита
//!   **сервера** от чужого трафика; клиенту, которому нужно принять только
//!   свой же ответ от одного сервера, она без надобности (подробности —
//!   [`udp2022::datagram`]).
//! - **Обновление сессии на середине потока** (TCP `KeyUpdate`-подобных
//!   механизмов у 2022 нет вовсе — рукопожатие одно на соединение) здесь и не
//!   нужно было решать: протокол сам устроен так, что сеансовый ключ живёт
//!   ровно одно соединение.
//!
//! **Тесты — на записанных байтах.** Вывод ключа BLAKE3 (`kdf2022`) проверен
//! официальным вектором BLAKE3 (`BLAKE3-team/BLAKE3`,
//! `test_vectors/test_vectors.json`) — он не про Shadowsocks, а про саму
//! функцию `derive_key`, но это ровно то, что вызывает `kdf2022::derive`;
//! записанного вектора подключа с меткой `"shadowsocks 2022 session subkey"`
//! здесь нет и не может быть — взять его неоткуда без живого сервера, а
//! посчитать самим значило бы проверить реализацию её же выводом. Блочный
//! AES (заголовок UDP AES-GCM) сверен с FIPS-197 (Appendix C.1, C.3);
//! `XChaCha20-Poly1305` — с `draft-irtf-cfrg-xchacha` (Appendix A.1, через
//! сам крейт `chacha20poly1305`, а не нашу обёртку с пустым `AAD`, — для неё
//! ниже отдельный круговой прогон). Отвергнутая метка времени, раскладка
//! заголовков TCP и UDP и проверка длины ключа в `validate` — круговым
//! прогоном и разбором на записанных байтах, что для формата без внешнего
//! вектора (структура кадра, а не число) — ровно то, что можно проверить.
//!
//! **О живой сервер не проверялось.** Ни сервера, ни готового захваченного
//! пакета от настоящей реализации 2022 под рукой нет; «подключилось в
//! тесте» здесь означает «наш клиент понимает то, что написал бы наш же
//! сервер», а не «сервер `shadowsocks-rust` принял наше соединение».

