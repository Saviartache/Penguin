//! Классификация ошибок, общая для всех слоёв: что показать пользователю и стоит ли повторять.

use thiserror::Error;

/// Результат операции над доменными типами.
pub type CoreResult<T> = Result<T, CoreError>;

/// Ошибка разбора или проверки доменного типа.
///
/// Здесь только то, что может пойти не так с самими данными. Сетевые и
/// файловые ошибки живут в тех крейтах, которые с сетью и файлами работают.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum CoreError {
    /// Строка не разбирается как адрес.
    #[error("не разбирается как адрес: {0}")]
    InvalidAddress(String),

    /// Порт вне допустимого диапазона или список портов пуст.
    #[error("неверный порт или диапазон портов: {0}")]
    InvalidPort(String),

    /// Значение вне допустимых пределов.
    #[error("{field}: ожидалось {expected}, получено {got}")]
    OutOfRange {
        /// Имя поля.
        field: &'static str,
        /// Что ожидалось.
        expected: &'static str,
        /// Что пришло.
        got: String,
    },
}

/// Насколько ошибка серьёзна для пользователя.
///
/// Существует ради интерфейса: «нет сети» и «неверный пароль» требуют разных
/// действий, и решать это по тексту сообщения нельзя.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Severity {
    /// Само пройдёт: клиент уже повторяет попытку.
    Transient,
    /// Нужно вмешательство пользователя: пароль, адрес сервера, права.
    UserAction,
    /// Сломано так, что дальше работать нельзя.
    Fatal,
}
