//! Ошибки клиента подписки, разложенные по вариантам (`AGENTS.md` §4.1).

use thiserror::Error;

/// Что пошло не так при работе со шлюзом подписки.
///
/// Секретов не несёт: ключ подписки и приватные ключи в тексты не попадают
/// (`AGENTS.md` §5.2).
#[derive(Debug, Error)]
pub enum SubscriptionError {
    /// Ключ `vpn://…` не разобран: не тот префикс, не base64url, не JSON.
    #[error("ключ подписки не разобран: {0}")]
    Key(String),

    /// Не собрать конверт запроса: неверный ключ шлюза или сбой RSA.
    #[error("конверт запроса не собран: {0}")]
    Envelope(String),

    /// Ответ шлюза не расшифровался тем же ключом (блокировка, не тот ключ шлюза).
    #[error("ответ шлюза не расшифрован")]
    Decrypt,

    /// Тело ответа разобрано, но не содержит ожидаемого конфига.
    #[error("ответ шлюза не разобран: {0}")]
    Response(String),

    /// Шлюз отказал полем `http_status` в теле: 429 лимит, 422 подписка истекла,
    /// 501 старая версия, 403 неверный ключ API и т. п. Сообщение — от шлюза.
    #[error("шлюз отказал ({status}): {message}")]
    Gateway {
        /// Код из поля `http_status`.
        status: i64,
        /// Текст из поля `message`.
        message: String,
    },

    /// Шлюз требует капчу — в консоли решить нельзя.
    #[error("шлюз требует капчу")]
    Captcha,

    /// Подписка на протокол, которого клиент не умеет.
    #[error("{0}")]
    Unsupported(String),

    /// Сбой сети при обращении к шлюзу.
    #[error("шлюз недоступен: {0}")]
    Http(String),
}

/// Результат операций клиента подписки.
pub type SubscriptionResult<T> = Result<T, SubscriptionError>;
