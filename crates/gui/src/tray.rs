//! Значок в лотке: чем клиент остаётся, когда окна на экране нет.
//!
//! Тоннель держит служба, а не окно, и спрятанный клиент продолжает работать.
//! Значок — единственное, по чему видно, что программа всё ещё здесь, и
//! единственный способ достать окно обратно: свёрнутого в лоток окна нет ни на
//! панели задач, ни в Alt+Tab.
//!
//! Само окно про лоток не знает ничего, кроме двух имён пунктов ниже: значок,
//! меню и события — забота кита ([`uikit::tray`]).

use uikit::tray::{Item, Tray};

/// Пункт «показать окно».
///
/// Обязателен: на Linux щелчок по значку событием не приходит вовсе, и без
/// пункта в меню окно оттуда не достать.
pub const SHOW: &str = "show";

/// Пункт «выход» — тот же выход, что и по красному кружку в шапке: со
/// остановкой службы.
pub const QUIT: &str = "quit";

/// Заводит значок.
///
/// `None` — лотка в системе нет, или значок не создался. Это не сбой: окно
/// тогда сворачивается на панель задач, как до всякого лотка.
pub fn create() -> Option<Tray> {
    let strings = crate::i18n::s();
    let menu = vec![
        Item::new(SHOW, strings.tray_show),
        Item::separator(),
        Item::new(QUIT, strings.tray_quit),
    ];

    match Tray::new(crate::window_icon()?, crate::app::TITLE, menu) {
        Ok(tray) => Some(tray),
        Err(err) => {
            tracing::warn!(%err, "значка в лотке не будет");
            None
        }
    }
}
