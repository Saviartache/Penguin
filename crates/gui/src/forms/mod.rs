//! Черновики форм: что человек набрал и во что это превращается.
//!
//! Отдельно от экранов намеренно. Экран решает, как поле выглядит; черновик —
//! что из набранного получится и почему оно пока не получается. Это разные
//! вопросы, и второй проверяется тестами без единого виджета.
//!
//! Обе формы устроены одинаково: `Draft` собирает введённое, `to_*` возвращает
//! готовое значение или **текст ошибки, который можно показать как есть**.
//! Разбирать код ошибки в интерфейсе всё равно некому, а показать причину надо
//! до нажатия «Сохранить», а не после.
//!
//! У формы сервера полей своих нет: их приносит описание протокола
//! ([`protocol`]). Так добавление протокола не трогает ни черновик, ни
//! редактор, ни разбор ссылок — только каталог.

