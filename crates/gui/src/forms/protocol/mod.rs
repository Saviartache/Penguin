//! Каталог протоколов: что окно умеет показать и как это ложится в настройки.
//!
//! # Зачем окну свой каталог
//!
//! Схему параметров знает сам протокол, и он же её проверяет
//! (`penguin_proto::factory::ProtocolFactory::validate`). Но спросить его окно
//! не может: `protocols/*` подключает один только `engine` (см. `AGENTS.md`,
//! §1), и стрелка отсюда туда означала бы, что каждый новый протокол правит
//! ещё и интерфейс.
//!
//! Поэтому здесь лежит **описание формы**, а не разбор параметров: какие поля
//! показать, как их подписать и куда в непрозрачном JSON положить набранное.
//! Настоящую проверку всё равно делает протокол — окно ловит только то, что
//! видно без сети: незаполненное обязательное поле и адрес, который не
//! разбирается.
//!
//! # Как добавить протокол
//!
//! Один файл рядом с этим — со своим [`ProtocolSpec`] — и одна строка в
//! [`catalog::ALL`]. Ни экран выбора, ни редактор, ни разбор ссылок при этом
//! не трогаются: они работают с описанием, а не с полями конкретного
//! протокола. Именно из-за этого свойства форма и переехала на описание —
//! до него добавление протокола означало правку `Draft`, `Field`, редактора и
//! всех их тестов разом.

