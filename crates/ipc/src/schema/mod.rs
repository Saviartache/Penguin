//! Схема сообщений.
//!
//! Это **контракт между двумя программами**, а не внутренний тип: демон и
//! интерфейс обновляются по отдельности, и после обновления одного из них по
//! разные стороны канала оказываются разные версии схемы.
//!
//! Отсюда правила. Новое поле — только необязательное, с умолчанием. Новый
//! вариант перечисления — только в конец. Удалять и переименовывать нельзя
//! вовсе: старая сторона перестанет понимать новую молча.

pub mod event;
pub mod request;
pub mod response;

pub use event::{Event, LogLevel};
pub use request::Request;
pub use response::{AppInfo, Explanation, ProbeResult, Response, RuleTrace, StatusReport};
