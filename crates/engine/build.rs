//! Собирает список фич, включённых в эту сборку, и отдаёт его коду.
//!
//! Нужен ради одного теста, но теста важного. Протоколов будет двадцать шесть,
//! и главная ошибка при добавлении — фича есть, зависимость подключилась,
//! крейт собрался, а строку регистрации в реестре забыли. Собирается такое без
//! единого предупреждения, а находится профилем «неизвестный протокол» у
//! человека, который ничего не менял.
//!
//! Перечислить фичи из самого кода нельзя: `cfg!(feature = ...)` требует
//! литерала, то есть списка, который тоже можно забыть пополнить. А Cargo
//! кладёт в среду сборки переменную `CARGO_FEATURE_<ИМЯ>` на **каждую**
//! включённую фичу — вот его и спрашиваем.
//!
//! Имя восстанавливается обратной заменой: Cargo поднимает регистр и заменяет
//! `-` на `_`. Значит, фича с настоящим подчёркиванием в имени приедет сюда
//! дефисом, и такие имена в этом крейте заводить нельзя — это проверяет тест
//! `crates/engine/tests/features.rs`, сверяя список с манифестом.

fn main() {
    let mut features: Vec<String> = std::env::vars()
        .filter_map(|(name, _)| {
            name.strip_prefix("CARGO_FEATURE_")
                .map(|feature| feature.to_ascii_lowercase().replace('_', "-"))
        })
        .collect();
    features.sort_unstable();

    println!("cargo:rustc-env=PENGUIN_FEATURES={}", features.join(","));
    println!("cargo:rerun-if-changed=build.rs");
}
