//! Fake-IP: домен получает адрес из служебной подсети до реального разрешения.
//!
//! Приём, без которого раздельное тоннелирование по доменам в режиме TUN не
//! работает. Приложение спрашивает у нас адрес и получает подставной; в
//! момент соединения мы по адресу узнаём имя обратно, и правило по домену
//! срабатывает — хотя в самом соединении никакого имени нет.
//!
//! ```text
//!   приложение ──запрос youtube.com──► клиент ──► 198.18.0.7
//!   приложение ──соединение с 198.18.0.7──► клиент ──► «это youtube.com»
//! ```
//!
//! Настоящее разрешение имени делает уже та сторона: сервер получает имя
//! целиком и разрешает его у себя. Провайдер при этом не видит ни одного
//! DNS-запроса.
//!
//! # Чего это стоит
//!
//! Приложение получает адрес, которого не существует. Те немногие, что сами
//! смотрят на полученный адрес и делают из него выводы, работать перестанут
//! — для них есть режим `resolve` в настройках.

pub mod mapping;
pub mod pool;

pub use mapping::FakeIpMap;
