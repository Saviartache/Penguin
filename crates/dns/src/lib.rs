//! Разрешение имён и защита от утечек DNS.
//!
//! Задач у крейта две, и вторая важнее первой.
//!
//! # Не дать именам утечь
//!
//! Тоннель шифрует трафик, но DNS-запрос уходит **мимо** него: система
//! спрашивает свои серверы напрямую. Провайдер при этом видит полный список
//! имён, которые открывает пользователь, — и никакого VPN для этого знания
//! ему не нужно. Лечится перехватом порта 53 из TUN ([`hijack`]).
//!
//! # Сохранить имя для правил
//!
//! Приложение разрешает имя заранее и открывает соединение к адресу — имени в
//! соединении уже нет, и правило «youtube.com в тоннель» применить не к чему.
//! Лечится подменой: имя получает адрес из служебной подсети, а в момент
//! соединения адрес разворачивается обратно в имя ([`fakeip`]).
//!
//! # Два разрешателя
//!
//! Их нельзя путать. **Основной** отвечает приложениям и работает через
//! тоннель. **Загрузочный** разрешает имя самого сервера и обязан ходить мимо
//! тоннеля — иначе замкнутый круг: чтобы поднять тоннель, нужен адрес
//! сервера; чтобы узнать адрес, нужен работающий тоннель.

