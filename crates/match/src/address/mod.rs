//! Сопоставление по адресу назначения.
//!
//! Четыре независимых способа спросить «куда идёт соединение»:
//!
//! - [`ip`] — адрес или подсеть; работает всегда, потому что адрес известен
//!   к моменту решения;
//! - [`domain`] — имя; работает, только пока имя известно (из DNS, подмены
//!   fake-IP или SNI);
//! - [`port`] — порт;
//! - `geo` — страна по базе GeoIP; без ссылки, потому что модуля может не
//!   быть: он живёт за фичей `geo`, а ссылка на отсутствующий модуль ломает
//!   сборку документации без неё.

pub mod domain;
#[cfg(feature = "geo")]
pub mod geo;
pub mod ip;
pub mod port;

pub use domain::DomainSet;
#[cfg(feature = "geo")]
pub use geo::{GeoIpDatabase, GeoIpSet};
pub use ip::IpSet;
pub use port::PortSet;
