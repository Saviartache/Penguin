//! Трейт `Matcher` и его результат.

use crate::target::MatchTarget;

/// Условие, которое либо подходит соединению, либо нет.
///
/// Никакого ввода-вывода: сопоставитель не ходит в DNS и не читает
/// `/proc`. Всё, что ему нужно, уже лежит в [`MatchTarget`]. Благодаря этому
/// весь набор правил проверяется на тестах без сети и без прав.
pub trait Matcher: Send + Sync + 'static {
    /// Подходит ли.
    fn matches(&self, target: &MatchTarget<'_>) -> bool;

    /// Короткое описание для объяснения решения в интерфейсе.
    fn describe(&self) -> String;
}
