//! Режим тоннелирования: всё, белый список, чёрный список, только правила.
//!
//! Сам тип живёт в [`penguin_config::schema::routing::TunnelMode`] — его
//! читают и пишут в файл настроек, а конфигурация лежит ниже маршрутизатора
//! по графу зависимостей.
//!
//! Здесь остаётся то, что относится уже к решению, а не к настройке:
//! [`crate::engine::default_decision`] — исход для соединения, не подошедшего
//! ни под одно правило.
//!
//! Главное про режим стоит повторить: это **только умолчание**. Правила
//! действуют всегда и всегда сильнее. Поэтому «белый и чёрный список
//! одновременно» — не отдельный режим и не отдельная ветка кода: просто
//! правила обоих действий в одном наборе, а разбирает их порядок
//! ([`crate::ruleset::order`]).

