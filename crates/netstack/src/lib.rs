//! Пользовательский стек TCP/IP поверх TUN: из пакетов получаются соединения.
//!
//! Система отдаёт клиенту голые IP-пакеты. Приложениям нужны соединения.
//! Этот крейт превращает одно в другое.
//!
//! # Два разных пути
//!
//! **TCP идёт через smoltcp.** Рукопожатие, окна, перепосылка, порядок — это
//! настоящая реализация TCP, и писать её самим незачем.
//!
//! **UDP идёт мимо.** Состояния у него нет, а сокет в стеке на каждую пару
//! адресов обошёлся бы дороже, чем разбор восьмибайтового заголовка: один
//! сокет приложения шлёт куда угодно.
//!
//! # Однопоточность
//!
//! Весь стек — одна задача, и это требование, а не упрощение: smoltcp не
//! рассчитан на обращение из нескольких потоков. Всё общение с движком идёт
//! через очереди, и наружу сокеты стека не выдаются никогда.
//!
//! ```text
//!   TUN ──пакеты──► [ устройство ──► smoltcp ──► сокеты ] ──очереди──► движок
//! ```

