//! Виртуальный сетевой интерфейс: чтение и запись IP-пакетов.
//!
//! Единственный способ забрать трафик приложений, которые про прокси ничего
//! не знают. Система видит обычный сетевой адаптер и, когда маршрут по
//! умолчанию ведёт через него, отдаёт клиенту все пакеты машины.
//!
//! ```text
//!   приложение ──► сетевой стек системы ──► TUN ──► клиент
//! ```
//!
//! Крейт отвечает ровно за последнюю стрелку: отдать пакет и принять пакет.
//! Что с ними делать, знает `penguin-netstack`; кто ставит маршруты —
//! `penguin-platform`.
//!
//! # Цена режима
//!
//! Права администратора, драйвер в поставке и необходимость аккуратно вернуть
//! маршруты на место при выходе. Взамен — работает со всем, включая
//! приложения без настроек прокси. Когда этого не нужно, есть
//! `penguin-inbound` с локальным прокси, которому не нужно ничего.

pub mod config;
pub mod device;
pub mod error;
pub mod packet;
pub mod platform;

pub use config::TunConfig;
