//! Команды.
//!
//! Все команды в этой группе работают сами по себе: ни демона, ни прав
//! администратора, ни драйвера им не нужно.
//!
//! - [`socks`] поднимает локальный прокси поверх профиля;
//! - [`profiles`] показывает профили и проверяет их настройки;
//! - [`rules`] показывает правила и объясняет решения;
//! - [`doctor`] проверяет окружение.
//!
//! Команды управления тоннелем обращаются к демону через канал управления:
//! тоннель держит он, а не эта программа.

pub mod doctor;
pub mod profiles;
pub mod rules;
pub mod socks;
