//! Отпечаток собранного файла.
//!
//! Служба держит в памяти тот образ, с которым её запустили. Положить рядом
//! новый `penguin.exe` мало: пока служба не перезапущена, тоннель поднимает
//! **прежний** код. Снаружи это выглядит хуже всего, что бывает, — исправление
//! есть, лежит на диске, а ошибка та же самая.
//!
//! Заметить это по версии нельзя: между сборками она не меняется, а файл
//! меняется. Поэтому сравнивается время правки файла — оно и отличает одну
//! сборку от другой, и у разработчика, и после обновления у пользователя.

/// Отпечаток файла, из которого запущена программа.
///
/// Пустая строка — узнать не удалось. Сравнивать с ней нельзя: сделать из
/// «не знаю» вывод «устарела» значит перезапускать службу без причины, а то и
/// по кругу.
pub fn stamp() -> String {
    let Ok(executable) = std::env::current_exe() else {
        return String::new();
    };
    let Ok(modified) = executable.metadata().and_then(|meta| meta.modified()) else {
        return String::new();
    };

    modified
        .duration_since(std::time::UNIX_EPOCH)
        .map(|since| since.as_secs().to_string())
        .unwrap_or_default()
}

/// Разошлись ли отпечатки настолько, что службу пора перезапустить.
///
/// Свободная функция с тестом: ошибка здесь означает либо службу, которая
/// навсегда осталась старой, либо перезапуск при каждом открытии окна.
pub fn is_stale(running: &str, current: &str) -> bool {
    // Хоть одна сторона молчит — вывода нет. Молчание не улика.
    if running.is_empty() || current.is_empty() {
        return false;
    }
    running != current
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_running_build_knows_itself() {
        // Пустой отпечаток у файла, который прямо сейчас работает, означал бы,
        // что проверка не работает вовсе.
        assert!(!stamp().is_empty());
    }

    #[test]
    fn different_stamps_mean_a_stale_service() {
        assert!(is_stale("1700000000", "1700000900"));
    }

    #[test]
    fn the_same_stamp_is_left_alone() {
        // Иначе служба перезапускалась бы при каждом открытии окна, роняя
        // тоннель.
        assert!(!is_stale("1700000000", "1700000000"));
    }

    #[test]
    fn silence_is_not_evidence() {
        // Старая служба отпечатка не сообщает вовсе — и перезапускать её по
        // одному этому нельзя: получится круг.
        assert!(!is_stale("", "1700000000"));
        assert!(!is_stale("1700000000", ""));
        assert!(!is_stale("", ""));
    }
}
