//! Системное окно выбора файла: им показывают программу, которая сейчас не
//! запущена.
//!
//! Список запущенного отвечает не на все вопросы. Правило пишут и для игры, в
//! которую сегодня не играли, и для обновлятора, который просыпается сам раз в
//! неделю: в списке их нет, а путь к ним человек наизусть не помнит — и уж тем
//! более не помнит, что внутри `Program Files` лежит ещё три каталога.
//!
//! Окно берётся системное, а не рисуется своё: своё пришлось бы учить сетевым
//! дискам, ярлыкам, правам на чужие каталоги и тому, что «Рабочий стол» лежит
//! не там, где написано.
//!
//! Вызов **держит поток**, пока человек не ответит. Звать его из потока
//! отрисовки нельзя: окно программы замрёт вместе с ним, и рядом с системным
//! окном будет стоять мёртвое наше.

#[cfg(target_os = "linux")]
mod linux;
#[cfg(target_os = "macos")]
mod macos;
#[cfg(windows)]
mod windows;

use std::path::PathBuf;

use crate::error::PlatformResult;

/// Просит человека показать программу.
///
/// `title` — заголовок окна, `filter` — как назван вид файлов в его списке.
/// Обе подписи приходят снаружи: переведены они в интерфейсе, и второй набор
/// переводов здесь разошёлся бы с первым.
///
/// `Ok(None)` — человек закрыл окно, ничего не выбрав. Это не ошибка, и
/// говорить ему об этом нечего: он и так знает, что нажал «Отмена».
pub fn pick_program(title: &str, filter: &str) -> PlatformResult<Option<PathBuf>> {
    #[cfg(windows)]
    {
        windows::pick_program(title, filter)
    }
    #[cfg(target_os = "linux")]
    {
        linux::pick_program(title, filter)
    }
    #[cfg(target_os = "macos")]
    {
        macos::pick_program(title, filter)
    }
    #[cfg(not(any(windows, target_os = "linux", target_os = "macos")))]
    {
        let _ = (title, filter);
        Err(crate::error::PlatformError::Unsupported("выбор файла"))
    }
}
