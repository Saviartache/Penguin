//! Перезапуск самого себя с правами администратора.
//!
//! Права ни одна из систем не выдаёт процессу на ходу: их получает только
//! новый процесс, запущенный особым образом. Поэтому «получить права» здесь
//! означает «запустить себя заново с нужной командой и дождаться» — через
//! окно UAC на Windows, polkit на Linux и системное окно на macOS.
//!
//! Просить их должно не всё подряд, а ровно то, чему они нужны: установка
//! службы, её запуск и остановка. Окно и проверки работают без прав и
//! спрашивать их не должны — лишний запрос приучает соглашаться, не читая.

#[cfg(target_os = "linux")]
mod linux;
#[cfg(target_os = "macos")]
mod macos;
#[cfg(windows)]
mod windows;

use crate::error::PlatformResult;

/// Запускает себя же с правами администратора и ждёт завершения.
///
/// `Ok(false)` — пользователь отказался. Это не ошибка: он имел право
/// отказаться, и ругаться на него незачем.
///
/// Аргументы передаются без кавычек: заключить их в них — забота той системы,
/// которая этого требует. На Windows командная строка одна на всех, и кавычки
/// нужны; на Linux и macOS программа запускается напрямую, и кавычка стала бы
/// частью имени каталога.
pub fn run_elevated(args: &[&str]) -> PlatformResult<bool> {
    #[cfg(windows)]
    {
        windows::run_elevated(args)
    }
    #[cfg(target_os = "linux")]
    {
        linux::run_elevated(args)
    }
    #[cfg(target_os = "macos")]
    {
        macos::run_elevated(args)
    }
    #[cfg(not(any(windows, target_os = "linux", target_os = "macos")))]
    {
        let _ = args;
        Err(crate::error::PlatformError::Unsupported("повышение прав"))
    }
}
