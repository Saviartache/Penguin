//! Миграция на схему версии 1.
//!
//! Версия 0 — это файл без поля `version`: либо самый первый конфиг клиента,
//! либо написанный руками по документации. Переносить в нём нечего, кроме
//! самого номера версии, но шаг всё равно заводится сразу: цепочку миграций
//! проще держать полной с первого дня, чем вспоминать про неё, когда файлов
//! у пользователей уже накопилось.

use crate::schema::RootConfig;

/// Поднимает файл версии 0 до версии 1.
pub fn from_v0(mut config: RootConfig) -> RootConfig {
    config.version = 1;
    config
}
