//! Демонизация и сигналы.
//!
//! На systemd демонизировать не нужно и вредно: служба должна оставаться на
//! переднем плане, а журнал писать в стандартный поток — этим занимается сам
//! systemd. Поэтому здесь запуск ничем не отличается от обычного, кроме
//! источника сигнала остановки.

use std::path::PathBuf;

use anyhow::Result;

/// Запускает демона под управлением systemd.
pub fn run(config_dir: Option<PathBuf>) -> Result<()> {
    // Ровно то же самое, что и на переднем плане: systemd шлёт `SIGTERM`,
    // который tokio разбирает как обычный сигнал.
    crate::runtime::run_foreground(config_dir, false)
}
