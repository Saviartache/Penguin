//! Ошибки протокола в терминах, понятных вышележащим слоям.

use thiserror::Error;

/// Что пошло не так при работе с протоколом.
///
/// Разделение не косметическое: по нему `supervisor` решает, повторять ли
/// попытку. Неверный пароль повторять бессмысленно, обрыв сети — обязательно.
#[derive(Debug, Error)]
pub enum ProtocolError {
    /// В конфигурации нет такого протокола.
    #[error("неизвестный протокол: {0}")]
    UnknownProtocol(String),

    /// Параметры не разбираются или противоречивы.
    #[error("неверные параметры протокола: {0}")]
    InvalidConfig(String),

    /// Сервер отверг учётные данные. Повторять не нужно.
    #[error("сервер отклонил аутентификацию")]
    AuthRejected,

    /// Не удалось установить соединение с сервером.
    #[error("не удалось подключиться к серверу: {0}")]
    Connect(String),

    /// Соединение оборвалось во время работы.
    #[error("соединение потеряно: {0}")]
    Disconnected(String),

    /// Целевой адрес недостижим со стороны сервера.
    #[error("адрес недостижим: {0}")]
    Unreachable(String),

    /// Направление не умеет то, о чём его попросили.
    #[error("протокол не поддерживает {0}")]
    Unsupported(&'static str),

    /// Ошибка ввода-вывода.
    #[error(transparent)]
    Io(#[from] std::io::Error),
}

impl ProtocolError {
    /// Стоит ли повторять попытку.
    pub fn is_retryable(&self) -> bool {
        matches!(
            self,
            Self::Connect(_) | Self::Disconnected(_) | Self::Unreachable(_) | Self::Io(_)
        )
    }
}
