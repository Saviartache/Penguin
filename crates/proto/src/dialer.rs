//! `Dialer` — как протокол выходит наружу в обход собственного тоннеля.
//!
//! Без этого получается петля. TUN перехватывает весь трафик машины, включая
//! QUIC-пакеты самого Hysteria 2 к своему серверу; те попадают обратно в
//! тоннель, который ещё не установлен, и подключение не поднимается никогда.
//!
//! Лечится это не маршрутом-исключением к IP сервера — маршрут ломается при
//! смене порта (port hopping) и при переезде сервера, — а тем, что протокол
//! вообще не открывает сокеты сам. Сокет ему выдаёт `Dialer`, привязанный к
//! физическому интерфейсу и помеченный так, чтобы правила брандмауэра узнавали
//! его и пропускали мимо тоннеля.

use std::net::{IpAddr, SocketAddr};

use async_trait::async_trait;
use tokio::net::{TcpStream, UdpSocket};

use crate::error::ProtocolError;

/// Выход наружу мимо тоннеля.
///
/// Реализацию даёт `penguin-engine`; протокол получает её при создании и
/// больше нигде сокетов не заводит. Это же свойство проверяется на ревью:
/// `std::net`/`tokio::net` в крейте протокола — ошибка.
#[async_trait]
pub trait Dialer: Send + Sync + 'static {
    /// Открывает TCP-соединение мимо тоннеля.
    async fn dial_tcp(&self, addr: SocketAddr) -> Result<TcpStream, ProtocolError>;

    /// Открывает UDP-сокет мимо тоннеля.
    ///
    /// `local` задаёт семейство адресов; порт обычно нулевой.
    async fn bind_udp(&self, local: SocketAddr) -> Result<UdpSocket, ProtocolError>;

    /// Разрешает имя сервера мимо тоннеля.
    ///
    /// Та же петля, что и с сокетами, только злее. Системный резолвер шлёт
    /// запрос через сетевой стек, то есть через TUN, то есть в ещё не
    /// поднятый тоннель — и адрес сервера, к которому этот тоннель надо
    /// поднять, не разрешается никогда.
    ///
    /// Поэтому имя сервера разрешает не протокол и не система, а тот, кто
    /// умеет спросить у резолвера в обход тоннеля.
    async fn resolve(&self, host: &str) -> Result<Vec<IpAddr>, ProtocolError>;
}
