//! `PacketOutbound` — направление, работающее на IP-пакетах, а не на потоках.
//!
//! WireGuard, OpenConnect и `CONNECT-IP` из MASQUE не открывают потоков и не
//! знают слова «соединение». Они дают виртуальный интерфейс: сюда пакет —
//! оттуда пакет. Заворачивать такие пакеты в [`Outbound`] и обратно — чистая
//! потеря: TCP поверх TCP тормозит там, где теряет пакеты нижний, и лечится
//! это только тем, чтобы нижнего не было.
//!
//! # Как это становится соединениями
//!
//! Никак — здесь. Превращает пакеты в потоки **движок**: он и так держит
//! пользовательский стек TCP/IP ради TUN, и второй такой же внутри крейта
//! протокола означал бы `smoltcp` в зависимостях протокола.
//!
//! ```text
//!  приложение ──► TUN ──► стек ──► router ──► PacketOutbound ──► сервер
//!                                     │
//!                                     └────► Outbound ──────────► сервер
//! ```
//!
//! То есть протокол уровня пакетов остаётся ровно тем, чем он является:
//! трубой для пакетов. Всё, что знает про соединения, живёт выше.
//!
//! # Почему отдельный трейт, а не вариант в [`Outbound`]
//!
//! [`Outbound`] обещает `connect_tcp`. Протокол уровня пакетов не может его
//! выполнить, и заставить его вернуть «не умею» значило бы завести обещание,
//! которое треть реализаций не держит. Отдельный трейт делает разницу видимой
//! на сборке, а не на первом соединении.
//!
//! [`Outbound`]: crate::outbound::Outbound

use std::net::{Ipv4Addr, Ipv6Addr};

use async_trait::async_trait;
use bytes::Bytes;
use penguin_core::id::OutboundId;

use crate::error::ProtocolError;

/// Виртуальный интерфейс, который направление даёт внутри тоннеля.
///
/// Адреса приходят **от сервера**, а не из настроек: у WireGuard они в
/// конфигурации, а у OpenConnect выдаются при входе вместе с маршрутами.
/// Поэтому спрашивают их после подключения, а не до.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PacketInterface {
    /// Адрес IPv4 и длина префикса.
    pub ipv4: (Ipv4Addr, u8),
    /// Адрес IPv6, если сервер его выдал.
    pub ipv6: Option<(Ipv6Addr, u8)>,
    /// Наибольший пакет, который направление берёт целиком.
    ///
    /// У WireGuard это 1420 при внешних 1500: заголовок съедает
    /// восемьдесят байт. Соврать здесь — значит объявить приложению MSS,
    /// который не проходит, и получить страницу, которая грузится наполовину.
    pub mtu: u16,
}

/// Направление, работающее на IP-пакетах.
///
/// Реализация обязана быть разделяемой: одно направление на профиль
/// обслуживает весь трафик сразу.
#[async_trait]
pub trait PacketOutbound: Send + Sync + 'static {
    /// Идентификатор, под которым это направление известно маршрутизатору.
    fn id(&self) -> OutboundId;

    /// Имя протокола для журнала и интерфейса: `"wireguard"`.
    fn protocol(&self) -> &'static str;

    /// Каким интерфейсом направление выглядит изнутри.
    fn interface(&self) -> PacketInterface;

    /// Отправляет пакет в тоннель.
    ///
    /// Пакет длиннее [`PacketInterface::mtu`] — ошибка настройки того, кто
    /// его собрал, а не повод молча его обрезать.
    async fn send(&self, packet: &[u8]) -> Result<(), ProtocolError>;

    /// Ждёт следующий пакет из тоннеля.
    async fn recv(&self) -> Result<Bytes, ProtocolError>;

    /// Закрывает направление.
    ///
    /// У протоколов с рукопожатием, которое обновляется по таймеру, здесь же
    /// останавливается и задача обновления: без этого она переживает профиль.
    async fn close(&self) -> Result<(), ProtocolError> {
        Ok(())
    }
}

/// Фабрика протокола уровня пакетов.
///
/// Отдельная от [`ProtocolFactory`](crate::factory::ProtocolFactory) по той же
/// причине, по которой отдельный трейт направления: фабрика, умеющая собрать
/// то или это, обязывала бы каждый из двадцати с лишним потоковых протоколов
/// объявлять, что пакеты он не умеет.
#[async_trait]
pub trait PacketFactory: Send + Sync + 'static {
    /// Имя протокола в конфигурации: `"wireguard"`.
    fn protocol(&self) -> &'static str;

    /// Проверяет параметры, не создавая соединения.
    fn validate(&self, params: &serde_json::Value) -> Result<(), ProtocolError>;

    /// Собирает направление и поднимает тоннель.
    async fn build(
        &self,
        ctx: crate::factory::BuildContext,
        params: &serde_json::Value,
    ) -> Result<std::sync::Arc<dyn PacketOutbound>, ProtocolError>;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_interface_carries_the_mtu_the_tunnel_really_has() {
        // 1420 при внешних 1500 — это WireGuard. Объявить 1500 значит обещать
        // приложению MSS, который не проходит.
        let interface = PacketInterface {
            ipv4: (Ipv4Addr::new(10, 0, 0, 2), 32),
            ipv6: None,
            mtu: 1420,
        };
        assert!(interface.mtu < 1500);
        assert_eq!(interface.clone(), interface);
    }
}
