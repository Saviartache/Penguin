#!/usr/bin/env bash
#
# Собирает каталог, который можно отдать человеку.
#
#   ./scripts/package.sh
#
# Установщика тут нет намеренно (он в фазе 9 плана). Каталог самодостаточен:
# распаковал и запустил — ровно то, чем проверяют сборку до установщика.
#
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

DIST="dist/penguin"

echo "▶ драйвер"
./scripts/fetch-wintun.sh

echo
echo "▶ сборка"
cargo build --workspace --release

echo
echo "▶ раскладка"
# Чистится содержимое, а не сам каталог: в Windows его держит открытым кто
# угодно — проводник, антивирус, оболочка, — и удаление падает на ровном месте.
mkdir -p "$DIST"
rm -f "$DIST"/*

# `.exe` только на Windows; на остальных платформах суффикса нет.
SUFFIX=""
[[ "${OS:-}" == "Windows_NT" ]] && SUFFIX=".exe"

# Файл один. Кем ему быть — окном, службой или командой терминала — он решает
# сам по своим аргументам, и человеку об этом знать не надо.
#
# Иконка уже внутри него: её кладёт в ресурсы `crates/app/build.rs` при сборке
# выше. Отдельным файлом рядом её класть некуда — проводник смотрит в `.exe`.
cp "target/release/penguin${SUFFIX}" "$DIST/"

# Драйвер кладётся рядом с исполняемым файлом: `wintun::load()` ищет его по
# обычному пути поиска библиотек, то есть в каталоге программы.
cp assets/wintun/wintun.dll "$DIST/"

# Ни настроек, ни описания: настройки клиент заводит сам при первом запуске,
# и человеку в них лезть незачем. Лишний файл рядом с программой — это
# приглашение его открыть и что-нибудь там поправить.

echo
echo "▶ что получилось"
ls -la "$DIST"

TOTAL="$(du -sh "$DIST" | cut -f1)"
echo
echo "готово: $DIST ($TOTAL)"
