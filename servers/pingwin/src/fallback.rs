//! Прикрытие: что видит тот, кого сервер не узнал.
//!
//! Обычный сайт. Не отказ, не тишина и не разрыв — настоящий сайт, которому
//! соединение отдаётся целиком, вместе со всеми уже прочитанными байтами.
//!
//! # Почему прочитанное надо отдать
//!
//! Сервер прочитал `ClientHello`, чтобы понять, свой ли клиент. Прикрытие
//! этих байт не видело, и без них оно получит запрос без начала: ответит
//! ошибкой или закроет соединение — то есть поведёт себя не так, как повёл бы
//! себя, стоя тут в одиночку. Ровно эта разница и есть то, по чему сервер
//! находят.
//!
//! # Чем это отличается от честного обратного прокси
//!
//! Ничем — и в этом смысл. Сервер здесь именно обратный прокси, и лучшее
//! прикрытие — настоящий веб-сервер на той же машине, поднятый ради того,
//! чтобы на него можно было зайти браузером и увидеть сайт.

use tokio::io::AsyncWriteExt;
use tokio::net::TcpStream;

/// Отдаёт соединение прикрытию.
///
/// `seen` — всё, что сервер успел прочитать, прежде чем понял, что клиент
/// чужой.
pub async fn proxy(mut client: TcpStream, seen: Vec<u8>, cover: &str) {
    let mut upstream = match TcpStream::connect(cover).await {
        Ok(upstream) => upstream,
        Err(err) => {
            tracing::warn!(cover, %err, "прикрытие недоступно — соединение закрыто");
            return;
        }
    };

    if upstream.write_all(&seen).await.is_err() {
        return;
    }
    if let Err(err) = tokio::io::copy_bidirectional(&mut client, &mut upstream).await {
        tracing::trace!(cover, %err, "прикрытие закрыло соединение");
    }
}
