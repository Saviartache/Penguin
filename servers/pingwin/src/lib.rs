//! Сервер протокола Pingwin: опознание, мультиплексор, прикрытие.
//!
//! ```text
//!  config    настройки: где слушать, чей ключ, кого пускать
//!  policy    правила: таблица пользователей и окно повторов
//!  server    приём соединений и сессии
//!  relay     что делать с открытым потоком и датаграммным каналом
//!  fallback  прикрытие: что видит тот, кого не узнали
//! ```
//!
//! # Почему это отдельная программа
//!
//! Она стоит на другой машине и решает другую задачу: клиент поднимает
//! тоннель у пользователя, сервер принимает соединения и ходит наружу.
//! Общего у них ровно одно — формат провода, и он живёт в
//! `protocols/pingwin`, откуда его берут оба.
//!
//! Отсюда же и направление зависимостей (`AGENTS.md` §1): сервер зависит от
//! крейта протокола, от `penguin-core` и от `penguin-proto` — и ни от одного
//! крейта клиента. Обратной стрелки нет и быть не может: клиент про сервер не
//! знает вовсе.
//!
//! # Почему библиотека, а не один `main.rs`
//!
//! Чтобы приём соединений можно было проверить тестом, не запуская процесс.
//! Двоичный файл (`src/main.rs`) — разбор командной строки и запуск, и больше
//! в нём ничего нет.

pub mod config;
pub mod fallback;
pub mod policy;
pub mod relay;
pub mod server;

pub use config::{ServerConfig, User};
pub use policy::Policy;
pub use server::Server;
