//! Сервер протокола Pingwin: HTTP/3, опознание, статическое прикрытие.
//!
//! ```text
//!  config      настройки: где слушать, чей ключ, какой сертификат, кого пускать
//!  tls         QUIC сервера по файлам сертификата
//!  policy      таблица пользователей
//!  server      приём соединений
//!  connection  одно соединение: опознание, запросы, датаграммы
//!  relay       что делать с CONNECT и каналом датаграмм
//!  cover       прикрытие: статический сайт для тех, кого не узнали
//! ```
//!
//! # Почему это отдельная программа
//!
//! Она стоит на другой машине: клиент поднимает тоннель у пользователя,
//! сервер принимает соединения и ходит наружу. Общее у них — формат провода,
//! и он живёт в `protocols/pingwin` (`AGENTS.md` §1.6).
//!
//! # Почему библиотека, а не один `main.rs`
//!
//! Чтобы приём соединений можно было проверить тестом, не запуская процесс.

pub mod config;
mod connection;
pub mod cover;
pub mod policy;
pub mod relay;
pub mod server;
pub mod tls;

pub use config::{ServerConfig, User};
pub use policy::Policy;
pub use server::Server;
